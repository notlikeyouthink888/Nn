def flange_width(bw, hf, ln, sn):
    """عرض الشفة الفعّال لمقطع T — ACI 318-19 جدول 6.3.2.1.

    bw عرض العنق · hf سماكة البلاطة · ln البحر الصافي · sn المسافة الصافية
    لأقرب عنق مجاور. الإضافة **لكل جهة** = أصغر من 8hf و sn/2 و ln/8.
    """
    add = min(8.0 * hf, sn * 1000.0 / 2.0, ln * 1000.0 / 8.0)
    return bw + 2.0 * max(0.0, add), add


def stirrup_legs(bw, d):
    """عدد أرجل الأساور من **عرض المقطع** — ACI 25.7.2.3 + 9.7.6.2.2.

    كل سيخ طولي بديل يجب أن يُسنَد بركن أسوار، والتباعد العرضي بين الأرجل
    لا يتجاوز الأصغر من d و600 مم. فرجلان تكفيان جسراً بعرض 300 مم ولا
    تكفيان جسراً مخفياً بعرض 900 مم — وهذا ما كان يُغفَل.
    """
    smax = min(max(d, 1.0), 600.0)
    legs = int(math.ceil((bw - 80.0) / smax)) + 1
    return max(2, min(10, legs)), smax


def hanger(w_hung, fy, phi=0.75):
    """حديد التعليق للجسر المقلوب — الحمل يدخل من **أسفل** المقطع.

    البلاطة تستند على الوجه السفلي للجسر المقلوب، فحملها يُعلَّق ولا يُسنَد:
    لولا أساور تعبر كامل العمق لانفصل الوجه السفلي بشقّ أفقي. تُصمَّم
    الأساور لحمل كامل الحمل المعلَّق إضافةً إلى القصّ (تعليق R9.7.6.2.2).
    Av/s المطلوبة بـ مم²/م.
    """
    return dict(w=w_hung, Av_s=w_hung * 1000.0 / (phi * fy) * 1000.0 / 1000.0,
                note='حمل البلاطة يدخل الجسر من وجهه **السفلي**، فيجب «تعليقه» '
                     'إلى منطقة الضغط العليا بأساور تعبر كامل العمق. وهذه '
                     'الأساور **تُضاف** على أساور القصّ ولا تحلّ محلّها.',
                clause='ACI 318-19 تعليق R9.7.6.2.2 (التحميل غير المباشر)')


def deep_web(bw, fy):
    """الحديد الموزّع بوجهي الجسر العميق — ACI 9.9.3.1."""
    return dict(Av_min=0.0025 * bw, Avh_min=0.0025 * bw,
                s_max=min(300.0, 0.0), clause='ACI 318-19 9.9.3.1 و9.9.4',
                note='الجسر العميق يُصمَّم بنموذج **الدعامة والرباط** (الفصل 23) '
                     'لا بنظرية الانحناء، ويلزمه حديد موزّع بالوجهين: '
                     'Av ≥ 0.0025·bw·s رأسياً و Avh ≥ 0.0025·bw·s₂ أفقياً، '
                     'وتباعدهما لا يتجاوز الأصغر من d/5 و300 مم.')


def width_cap(col_b, col_h, h):
    """أقصى عرض جسر بإطار مقاوم للعزوم — ACI 318-19 المادة 18.6.2.1.

    العرض لا يتجاوز عرض العمود الساند زائد مسافة بكل جهة = الأصغر من عرض
    العمود و0.75 من بُعده. وما زاد لا يصل حمله للعقدة فعلياً.
    """
    add = min(col_b, 0.75 * col_h)
    return col_b + 2.0 * add, add


def spec(key, ctx):
    """كل ما يتغيّر بتغيّر نوع الجسر — هندسةً وتسليحاً وفحوصاً."""
    T = TYPE_MAP.get(key) or TYPE_MAP['drop']
    span = float(ctx['span']); slab_h = float(ctx['slab_h'])
    col_b = float(ctx['col_b']); col_h = float(ctx.get('col_h', col_b))
    fy = float(ctx.get('fy', 420.0))
    sn = float(ctx.get('clear_span_side', 4.0))     # المسافة الصافية لأقرب عنق
    ln = max(0.5, span - col_b / 1000.0)
    out = dict(T)
    out['ln'] = ln

    # ---- ١ · هندسة المقطع: العمق والعرض ----
    if key == 'hidden':
        h = slab_h                                   # العمق = سماكة السقف بالضبط
        bw = max(400.0, min(2.5 * col_b, 1200.0))
        out['h_rule'] = ('العمق **مقيَّد** بسماكة السقف %d مم — لا يُختار، '
                         'والعرض هو المتغيّر الوحيد' % int(slab_h))
    elif key == 'wide':
        h = max(slab_h + 100.0, math.ceil(span * 1000.0 / 18.0 / 50.0) * 50.0)
        bw = max(350.0, min(2.0 * col_b, 900.0))
        out['h_rule'] = 'عمق متوسط ≈ البحر/18 مع بروز محدود تحت السقف'
    elif key == 'deep':
        h = max(slab_h + 200.0, math.ceil(ln * 1000.0 / 4.0 / 50.0) * 50.0)
        bw = max(300.0, min(col_b, 500.0))
        out['h_rule'] = 'العمق كبير حتى يصير ln/h ≤ 4 — وهو تعريف الجسر العميق (9.9.1.1)'
    else:                                            # drop · inverted · spandrel
        h = max(400.0, math.ceil(span * 1000.0 / 12.0 / 50.0) * 50.0)
        bw = max(250.0, min(col_b, 400.0))
        out['h_rule'] = 'العمق ≈ البحر/12 والعرض ≤ عرض العمود — المقطع المألوف'
    cap, cap_add = width_cap(col_b, col_h, h)
    # العرض يبدأ **داخل** الحدّ الكودي لا فوقه: ما زاد على c2 + 2·min(c2, 0.75c1)
    # لا يصل حمله للعقدة فعلياً، فلا فائدة من تعريض يتجاوزه.
    bw = min(bw, cap)
    out.update(h0=h, bw0=bw, width_cap=cap, width_add=cap_add,
               width_ok=bw <= cap + 1e-6)

    # ---- ٢ · الشفة: لأي إشارة عزم تعمل البلاطة ضاغطة ----
    bf, add = flange_width(bw, slab_h, ln, sn)
    out['flange'] = dict(bf=bf, add=add, hf=slab_h,
                         pos=T['flange_pos'], neg=T['flange_neg'],
                         clause='ACI 318-19 جدول 6.3.2.1',
                         note=('البلاطة **فوق** الجسر فتضغط مع العزم الموجب: '
                               'المقطع T بعرض شفة %d مم' % int(bf))
                              if T['flange_pos'] else
                              ('البلاطة **تحت** الجسر فتضغط مع العزم السالب: '
                               'المقطع T **عند المساند** بعرض شفة %d مم، '
                               'ومستطيل بعرض العنق %d مم بوسط البحر'
                               % (int(bf), int(bw)))
                              if T['flange_neg'] else
                              ('لا شفة: البلاطة بمستوى الجسر لا فوقه ولا تحته، '
                               'فالمقطع مستطيل %d مم بالوجهين' % int(bw)))
    out['bf_pos'] = bf if T['flange_pos'] else bw
    out['bf_neg'] = bf if T['flange_neg'] else bw

    # ---- ٣ · الأساور: عدد الأرجل من العرض ----
    d0 = h - 40.0 - 10.0 - 10.0
    legs, s_tr = stirrup_legs(bw, d0)
    out['legs'] = legs
    out['legs_rule'] = ('عرض المقطع %d مم والتباعد العرضي المسموح بين الأرجل '
                        '%d مم (الأصغر من d و600) ⇒ **%d أرجل** (25.7.2.3)'
                        % (int(bw), int(s_tr), legs))

    # ---- ٤ · تفاصيل خاصّة بالنوع ----
    extras = []
    if key == 'inverted':
        w_h = float(ctx.get('w_slab', 0.0))
        hg = hanger(w_h, fy)
        out['hanger'] = hg
        extras.append('حديد تعليق (Hanger) بكامل العمق — %s' % hg['clause'])
    if key == 'deep':
        out['deep'] = deep_web(bw, fy)
        extras.append('حديد موزّع بالوجهين + نموذج دعامة ورباط — 9.9.3.1 و الفصل 23')
    if T['torsion']:
        extras.append('الالتواء إلزامي: أساور **مغلقة** + حديد طولي على المحيط — 22.7')
    if key == 'hidden':
        extras.append('الترخيم حاكم: العمق أقلّ من أدنى سماكة الجدول 9.3.1.1، '
                      'فيجب حسابه لا الاكتفاء بالسماكة (9.3.1.1.1)')
        extras.append('القصّ حرج: d صغير فـ φVc صغير — تُقارَب الأساور وتُزاد أرجلها')
    out['extras'] = extras

    # ---- ٥ · موضع المقطع من البلاطة (للرسم والتنفيذ) ----
    #   top    = ظهر الجسر بمستوى ظهر البلاطة (ساقط)
    #   in     = الجسر داخل سماكة البلاطة (مخفي)
    #   bottom = بطن الجسر بمستوى بطن البلاطة (مقلوب)
    out['offset'] = {'top': 0.0, 'in': 0.0, 'bottom': h - slab_h}[T['slab']]
    out['drop_below'] = max(0.0, h - slab_h) if T['slab'] == 'top' else 0.0
    out['rise_above'] = max(0.0, h - slab_h) if T['slab'] == 'bottom' else 0.0
    return out

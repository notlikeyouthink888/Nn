"""
calcdoc.py — اشتقاق الحسابات خطوةً خطوة، بالمعادلة ونصّ البند.

الغرض ليس إعطاء الرقم بل **إعطاء طريق الوصول إليه**: المعادلة الرمزية، ثم
التعويض بالأرقام، ثم الناتج، ثم رقم البند الكودي والحدّ الذي يفرضه ولماذا.
وهذا هو الفرق بين برنامجٍ يقول «العدد 21» وبرنامجٍ يجعل المهندس يقدر يدقّق
السطر بنفسه ويحاجّ به.

كل دالّة هنا ترجع «وثيقة حساب» بالصيغة:

    {title, intro, steps: [...], result: {...}, refs: [...]}

والخطوة الواحدة:

    {n, title, formula, subst, result, unit, clause, code, state}
        formula = المعادلة الرمزية      ·  subst = التعويض بالأرقام
        clause  = رقم البند             ·  code  = ما يفرضه البند بالضبط
        state   = ok | warn | fail | info | gov   (gov = هذا البند هو الحاكم)

كل الاستشهادات هنا **ACI 318-19**. ونصوص البنود مصوغة بألفاظنا لا منقولة،
مع رقم البند ليرجع إليه القارئ في نسخته.
"""
import math

AR = '٠١٢٣٤٥٦٧٨٩'


def _ar(n):
    """رقم عربي هندي لترقيم الخطوات."""
    return ''.join(AR[int(c)] for c in str(n))


def step(i, title, formula, subst, result, unit='', clause='', code='', state='ok'):
    return dict(n=_ar(i), title=title, formula=formula, subst=subst,
                result=result, unit=unit, clause=clause, code=code, state=state)


def renumber(steps):
    """يعيد ترقيم الخطوات تسلسلياً — لتخطّي خطوةٍ اختيارية لا يترك فجوة."""
    for i, s in enumerate(steps):
        s['n'] = _ar(i + 1)
    return steps


def _f(v, d=2):
    if v is None:
        return '—'
    return ('%.' + str(d) + 'f') % v


# ═══════════════════════ ١) عدد الأسياخ بالتباعد ═══════════════════════
def bar_count(L, s, cover=0.0, what='البلاطة', db=0.0):
    """عدد الأسياخ على عرض L بتباعد s.

        n = (L / s) + 1  ثمّ يُقرَّب **لأعلى**

    والتقريب لأعلى لا لأدنى: لو قُرِّب لأدنى لخرجت المسافة الفعلية بين
    الأسياخ **أكبر** من تباعد التصميم، فيسقط ما صُمِّم عليه المقطع.

    والعدد الدقيق يطرح الغطاء من الطرفين، لأن السيخ الأول والأخير يقفان
    داخله: n = ⌈(L − 2c) / s⌉ + 1. تُعرض القيمتان معاً ويُؤخذ الأكبر.

    L و s و cover بالمتر · النتيجة عدد صحيح.
    """
    steps = []
    n_simple = math.ceil(L / s) + 1 if s > 0 else 0
    steps.append(step(
        1, 'العدد بقاعدة التباعد',
        'n = ( L ÷ s ) + 1\nL = الطول أو العرض الكلي   ·   s = تباعد التصميم',
        'n = ( %s ÷ %s ) + 1 = %s + 1 = %s' % (_f(L, 3), _f(s, 3),
                                               _f(L / s, 2) if s else '—',
                                               _f(L / s + 1, 2) if s else '—'),
        '%d سيخ' % n_simple, '',
        'قاعدة التنفيذ', 'التقريب **لأعلى** دائماً: التقريب لأدنى يجعل المسافة '
        'الفعلية أكبر من تباعد التصميم فيسقط الافتراض الذي صُمِّم عليه المقطع.',
        'info'))

    Lnet = max(0.0, L - 2 * cover)
    n_exact = math.ceil(Lnet / s) + 1 if s > 0 else 0
    if cover > 0:
        steps.append(step(
            2, 'العدد الدقيق بخصم الغطاء',
            'L_net = L − 2·c   ·   n = ⌈ L_net ÷ s ⌉ + 1',
            'L_net = %s − 2×%s = %s م  →  n = ⌈%s÷%s⌉ + 1 = %d'
            % (_f(L, 3), _f(cover, 3), _f(Lnet, 3), _f(Lnet, 3), _f(s, 3), n_exact),
            '%d سيخ' % n_exact, '',
            'ACI 318-19 §20.5.1', 'السيخ الطرفي يقف داخل الغطاء الخرساني، '
            'فالمسافة القابلة للتوزيع هي L ناقص الغطاء من الجهتين.', 'info'))

    n = max(n_simple, n_exact)
    s_act = (Lnet / (n - 1)) if n > 1 and Lnet > 0 else s
    steps.append(step(
        3 if cover > 0 else 2, 'العدد المعتمَد والتباعد الفعلي',
        's_act = L_net ÷ ( n − 1 )',
        's_act = %s ÷ (%d − 1) = %s م' % (_f(Lnet if cover > 0 else L, 3), n,
                                          _f(s_act, 4)),
        '%d سيخ @ %s مم' % (n, _f(s_act * 1000, 0)), '',
        'تحقّق', ('التباعد الفعلي %s مم ≤ تباعد التصميم %s مم ✓'
                  % (_f(s_act * 1000, 0), _f(s * 1000, 0)))
        if s_act <= s * 1.001 else
        ('⚠️ التباعد الفعلي %s مم يتجاوز تباعد التصميم %s مم'
         % (_f(s_act * 1000, 0), _f(s * 1000, 0))),
        'ok' if s_act <= s * 1.001 else 'fail'))

    return dict(
        title='عدد أسياخ %s' % what,
        intro='عدد الأسياخ ليس اختياراً: هو ناتج **التباعد** الذي فرضه التصميم '
              'على العرض الكلي. والتباعد نفسه محكوم بحدود الكود أدناه.',
        steps=steps,
        result=dict(n=n, s_design=s, s_actual=s_act, L=L, Lnet=Lnet, db=db),
        refs=['ACI 318-19 §20.5.1 — الغطاء الخرساني',
              'ACI 318-19 §7.7.2.3 / §8.7.2.2 — أقصى تباعد لحديد البلاطات'])


# ═══════════════════ ٢) حدود تباعد حديد البلاطة ═══════════════════
def slab_spacing_limits(h, cover, db, fy=420.0, kind='two'):
    """أقصى تباعد مسموح لحديد البلاطة — والتباعد المختار يجب ألّا يتجاوزه."""
    steps = []
    lim1 = min(3 * h, 0.450)               # §8.7.2.2 للبلاطات ثنائية الاتجاه
    lim2 = min(2 * h, 0.450) if kind != 'two' else lim1
    lim = lim1 if kind == 'two' else lim2
    steps.append(step(
        1, 'أقصى تباعد لحديد الانحناء الرئيسي',
        's ≤ min( %d·h , 450 مم )' % (3 if kind == 'two' else 2),
        's ≤ min( %d×%s , 450 ) = %s مم' % (3 if kind == 'two' else 2,
                                            _f(h * 1000, 0), _f(lim * 1000, 0)),
        '%s مم' % _f(lim * 1000, 0), '',
        'ACI 318-19 §8.7.2.2' if kind == 'two' else 'ACI 318-19 §7.7.2.3',
        'البلاطة ثنائية الاتجاه: التباعد ≤ 3h ولا يتجاوز 450 مم. '
        'أحادية الاتجاه: ≤ 3h كذلك عند المقاطع الحرجة و≤ 450 مم.'
        if kind == 'two' else
        'البلاطة أحادية الاتجاه: حديد الانحناء ≤ 3h ولا يتجاوز 450 مم.',
        'gov'))
    lim_t = min(5 * h, 0.450)
    steps.append(step(
        2, 'أقصى تباعد لحديد الانكماش والحرارة',
        's ≤ min( 5·h , 450 مم )',
        's ≤ min( 5×%s , 450 ) = %s مم' % (_f(h * 1000, 0), _f(lim_t * 1000, 0)),
        '%s مم' % _f(lim_t * 1000, 0), '',
        'ACI 318-19 §24.4.3.3',
        'حديد الانكماش والحرارة تباعده أوسع لأن دوره ضبط التشقّق لا حمل العزم.',
        'info'))
    rho_t = 0.0018 if fy >= 420 else 0.0020
    steps.append(step(
        3, 'أدنى نسبة لحديد الانكماش والحرارة',
        'ρ_min = %s   ·   As,min = ρ_min · b · h' % _f(rho_t, 4),
        'As,min = %s × 1000 × %s = %s مم²/م'
        % (_f(rho_t, 4), _f(h * 1000, 0), _f(rho_t * 1000 * h * 1000, 0)),
        '%s مم²/م' % _f(rho_t * 1000 * h * 1000, 0), '',
        'ACI 318-19 جدول 24.4.3.2',
        'لحديد مشوّه بإجهاد خضوع fy = 420 MPa تكون النسبة 0.0018. '
        'وللفولاذ الأدنى إجهاداً ترتفع النسبة.', 'info'))
    return dict(title='حدود تباعد حديد البلاطة', intro='', steps=steps,
                result=dict(s_max=lim, s_max_temp=lim_t, rho_temp=rho_t),
                refs=['ACI 318-19 §7.7.2.3 · §8.7.2.2 · §24.4.3.2 · §24.4.3.3'])


# ═══════════════════ ٣) الكانات في العمود ═══════════════════
def col_ties(H, b, h, db_long, db_tie, s_mid, s_conf, lo=None, hx=None,
             seismic=True, ln=None):
    """عدد الكانات (الأتاري) في عمود، بمناطقه الثلاث.

    القاعدة البسيطة `n = H/s + 1` **لا تكفي**، لأن التباعد ليس ثابتاً على طول
    العمود: ACI 318-19 §18.7.5 يفرض منطقة تطويق (ℓo) عند كل طرف بتباعد أضيق،
    لأن المفصل اللدن يتكوّن هناك عند الزلزال ويحتاج حصراً للخرسانة.

    فالعمود ثلاث مناطق:
        ℓo سفلية بتباعد s_o  ·  وسطى بتباعد s  ·  ℓo علوية بتباعد s_o

    كل الأبعاد بالمليمتر عدا H بالمتر.
    """
    Hmm_ = H * 1000.0
    lnn = (ln * 1000.0) if ln else Hmm_
    steps = []

    # ---- (١) القاعدة البسيطة، للمقارنة ----
    n_simple = math.ceil(Hmm_ / s_mid) + 1 if s_mid > 0 else 0
    steps.append(step(
        1, 'القاعدة البسيطة (تباعد واحد على كل الارتفاع)',
        'n = ( H ÷ s ) + 1\nH = ارتفاع العمود   ·   s = التباعد',
        'n = ( %s ÷ %s ) + 1 = %s + 1 = %s'
        % (_f(H, 2) + ' م', _f(s_mid / 1000.0, 2) + ' م',
           _f(Hmm_ / s_mid, 2), _f(Hmm_ / s_mid + 1, 2)),
        '%d كانة' % n_simple, '',
        'قاعدة التنفيذ',
        '⚠️ هذه القاعدة **ناقصة** للعمود المقاوم للزلازل: التباعد ليس ثابتاً. '
        'تُستعمل للمقارنة فقط، والحساب المعتمَد بالمناطق أدناه.', 'warn'))

    # ---- (٢) طول منطقة التطويق ℓo ----
    lo_req = max(h, b, lnn / 6.0, 450.0)
    lo_use = lo if lo else lo_req
    steps.append(step(
        2, 'طول منطقة التطويق ℓo عند كل طرف',
        'ℓo ≥ max( max(b , h) ,  ℓu ÷ 6 ,  450 mm )\nℓu = الارتفاع الصافي للعمود   ·   b , h = بُعدا المقطع',
        'ℓo ≥ max( %s , %s÷6 = %s , 450 ) = %s مم'
        % (_f(max(b, h), 0), _f(lnn, 0), _f(lnn / 6.0, 0), _f(lo_req, 0)),
        '%s مم' % _f(lo_use, 0), '',
        'ACI 318-19 §18.7.5.1',
        'المفصل اللدن يتكوّن عند طرفَي العمود، فيُطوَّق هذا الطول بأسوار متقاربة '
        'تحصر الخرسانة وتمنع انبعاج الحديد الطولي. الطول الحاكم هو الأكبر من '
        'ثلاثة: بُعد المقطع الأكبر · سُدس الارتفاع الصافي · 450 مم.',
        'gov' if abs(lo_use - lo_req) < 1 else 'ok'))

    # ---- (٣) تباعد الأسوار خارج منطقة التطويق ----
    s_lim = min(16.0 * db_long, 48.0 * db_tie, min(b, h))
    steps.append(step(
        3, 'أقصى تباعد للأسوار خارج منطقة التطويق',
        's ≤ min( 16·d_b,long ,  48·d_b,tie ,  min(b , h) )',
        's ≤ min( 16×%s = %s , 48×%s = %s , %s ) = %s مم'
        % (_f(db_long, 0), _f(16 * db_long, 0), _f(db_tie, 0),
           _f(48 * db_tie, 0), _f(min(b, h), 0), _f(s_lim, 0)),
        '%s مم' % _f(s_mid, 0), '',
        'ACI 318-19 §25.7.2.1',
        'ثلاثة حدود والحاكم أصغرها: 16 قطر سيخ طولي (يمنع انبعاجه) · '
        '48 قطر سوار · وأصغر بُعد للمقطع.',
        'ok' if s_mid <= s_lim + 1e-6 else 'fail'))

    # ---- (٤) تباعد التطويق داخل ℓo ----
    hx_use = hx if hx else max(b, h) - 2 * 40.0 - db_tie
    so = max(100.0, min(150.0, 100.0 + (350.0 - hx_use) / 3.0))
    s_conf_lim = min(b / 4.0, h / 4.0, 6.0 * db_long, so)
    steps.append(step(
        4, 'أقصى تباعد داخل منطقة التطويق s_o',
        's_o ≤ min( min(b , h) ÷ 4 ,  6·d_b,long ,  s_o(h_x) )\n'
        's_o(h_x) = 100 + ( 350 − h_x ) ÷ 3       و   100 ≤ s_o ≤ 150 mm',
        's_o = 100 + (350 − %s)÷3 = %s  →  s_o ≤ min( %s÷4 = %s , 6×%s = %s , %s ) = %s مم'
        % (_f(hx_use, 0), _f(so, 0), _f(min(b, h), 0), _f(min(b, h) / 4.0, 0),
           _f(db_long, 0), _f(6 * db_long, 0), _f(so, 0), _f(s_conf_lim, 0)),
        '%s مم' % _f(s_conf, 0), '',
        'ACI 318-19 §18.7.5.3',
        'h_x هو أكبر مسافة أفقية بين أسياخ مقيَّدة بزاوية سوار أو بقيد عرضي. '
        'كلما تباعدت الأسياخ الطولية لزم تضييق الأسوار. والحدّ لا ينزل تحت '
        '100 مم ولا يعلو 150 مم.',
        'ok' if s_conf <= s_conf_lim + 1e-6 else 'fail'))

    # ---- (٥) موضع أول سوار ----
    first = s_conf / 2.0
    steps.append(step(
        5, 'موضع أول سوار من وجه العقدة',
        's_first ≤ s_o ÷ 2',
        '%s ÷ 2 = %s مم' % (_f(s_conf, 0), _f(first, 0)),
        '%s مم' % _f(first, 0), '',
        'ACI 318-19 §18.7.5.3',
        'أول سوار يقع على نصف التباعد من وجه الجسر أو الأساس، لأن أقصى '
        'إجهاد يقع هناك بالضبط.', 'info'))

    # ---- (٦) العدّ بالمناطق ----
    n_o = int(math.ceil(lo_use / s_conf)) if s_conf > 0 else 0
    L_mid = max(0.0, Hmm_ - 2 * lo_use)
    n_m = max(0, int(math.ceil(L_mid / s_mid)) - 1) if s_mid > 0 else 0
    n_tot = 2 * n_o + n_m
    steps.append(step(
        6, 'عدّ الكانات بالمناطق الثلاث',
        'منطقة التطويق (كل طرف):  n_o = ⌈ ℓo ÷ s_o ⌉\n'
        'المنطقة الوسطى:           L_m = H − 2·ℓo   ·   n_m = ⌈ L_m ÷ s ⌉ − 1\n'
        'المجموع:                  n = 2·n_o + n_m',
        'n_o = ⌈%s ÷ %s⌉ = %d   (×2 طرفين)\n'
        'L_m = %s − 2×%s = %s مم   →   n_m = ⌈%s ÷ %s⌉ − 1 = %d\n'
        'n = 2×%d + %d = %d'
        % (_f(lo_use, 0), _f(s_conf, 0), n_o,
           _f(Hmm_, 0), _f(lo_use, 0), _f(L_mid, 0), _f(L_mid, 0), _f(s_mid, 0), n_m,
           n_o, n_m, n_tot),
        '%d كانة' % n_tot, '',
        'ACI 318-19 §18.7.5',
        'المنطقة الوسطى يُطرح منها واحد لأن الكانتين عند حدّيها محسوبتان ضمن '
        'منطقتَي التطويق، فلا تُعدّان مرّتين.', 'ok'))

    # ---- (٧) قطر السوار الأدنى ----
    db_min = 10.0 if db_long <= 32.0 else 13.0
    steps.append(step(
        7, 'أدنى قطر للسوار',
        'd_b,tie ≥ 10 mm      عند   d_b,long ≤ Ø32\n'
        'd_b,tie ≥ 13 mm      عند   d_b,long > Ø32  أو الحِزَم',
        'السيخ الطولي Ø%s  →  السوار ≥ %s مم  (المختار Ø%s)'
        % (_f(db_long, 0), _f(db_min, 0), _f(db_tie, 0)),
        'Ø%s' % _f(db_tie, 0), 'مم',
        'ACI 318-19 §25.7.2.2',
        'قطر السوار الأدنى مرتبط بقطر السيخ الطولي الذي يسنده.',
        'ok' if db_tie >= db_min - 1e-6 else 'fail'))

    return dict(
        title='عدد الكانات (الأتاري) في العمود',
        intro='القاعدة البسيطة «الارتفاع ÷ التباعد + 1» تصحّ لو كان التباعد '
              'واحداً — وهو ليس كذلك في عمودٍ مقاوم للزلازل. '
              '<b>ACI 318-19 §18.7.5</b> يفرض منطقة تطويق عند كل طرف بتباعد '
              'أضيق، لأن المفصل اللدن يتكوّن هناك. فالعدّ يكون بالمناطق.',
        steps=steps,
        result=dict(n=n_tot, n_conf_each=n_o, n_mid=n_m, lo=lo_use,
                    s_mid=s_mid, s_conf=s_conf, s_limit=s_lim,
                    s_conf_limit=s_conf_lim, first=first, n_simple=n_simple,
                    db_tie_min=db_min, so=so, hx=hx_use),
        refs=['ACI 318-19 §18.7.5.1 — طول منطقة التطويق ℓo',
              'ACI 318-19 §18.7.5.3 — تباعد التطويق s_o وموضع أول سوار',
              'ACI 318-19 §25.7.2.1 — أقصى تباعد للأسوار',
              'ACI 318-19 §25.7.2.2 — أدنى قطر للسوار'])


# ═══════════════════ ٤) الحديد الطولي للعمود ═══════════════════
def col_long(b, h, db, n_bars, Ast, fc, fy, cover=40.0, db_tie=10.0, Pu=None,
             Mu=None, phiPn=None, phiMn=None):
    """الحديد الطولي: النسبة وحدودها والعدد الأدنى والتباعد الصافي."""
    Ag = b * h
    rho = Ast / Ag if Ag else 0.0
    steps = []
    steps.append(step(
        1, 'نسبة الحديد الطولي ρ',
        'ρ = A_st ÷ A_g',
        'ρ = %s ÷ (%s × %s) = %s ÷ %s = %s'
        % (_f(Ast, 0), _f(b, 0), _f(h, 0), _f(Ast, 0), _f(Ag, 0), _f(rho, 5)),
        '%s %%' % _f(rho * 100, 2), '',
        'ACI 318-19 §10.6.1.1',
        'النسبة محصورة بين 1% و8% من مساحة المقطع الكلّية. الحدّ الأدنى '
        'يقاوم الزحف والانكماش وأثر العزوم غير المحسوبة، والأعلى لمنع '
        'ازدحام الحديد وتعذّر الصبّ.',
        'ok' if 0.01 - 1e-9 <= rho <= 0.08 + 1e-9 else 'fail'))
    steps.append(step(
        2, 'التحقّق من الحدّين',
        '0.01 ≤ ρ ≤ 0.08',
        '0.01 ≤ %s ≤ 0.08' % _f(rho, 5),
        '✓ ضمن الحدّين' if 0.01 <= rho <= 0.08 else '✗ خارج الحدّين', '',
        'ACI 318-19 §10.6.1.1',
        'للأعمدة المقاومة للزلازل يُنصح بألّا تتجاوز 6% عملياً لتيسير '
        'التراكب داخل المفصل (ACI 318-19 §18.7.4.1 يحدّها بـ 6%).',
        'ok' if rho <= 0.06 else 'warn'))
    n_min = 4 if True else 6
    steps.append(step(
        3, 'أدنى عدد للأسياخ الطولية',
        'المقطع المستطيل بأسوار مستطيلة: 4 أسياخ  ·  الدائري باللولب: 6 أسياخ',
        'العدد المختار %d سيخ' % n_bars,
        '%d سيخ Ø%s' % (n_bars, _f(db, 0)), '',
        'ACI 318-19 §10.7.3.1',
        'سيخ في كل زاوية على الأقل، ليعمل السوار على حصر الخرسانة فعلياً.',
        'ok' if n_bars >= n_min else 'fail'))
    nb_face = max(2, int(round((n_bars + 4) / 4.0)))
    clear = (b - 2 * cover - 2 * db_tie - nb_face * db) / max(1, nb_face - 1)
    cl_min = max(1.5 * db, 40.0)
    steps.append(step(
        4, 'المسافة الصافية بين الأسياخ',
        's_clear = ( b − 2c − 2·d_b,tie − n·d_b ) ÷ ( n − 1 )\n'
        'ويجب:  s_clear ≥ max( 1.5·d_b , 40 mm )',
        's_clear = ( %s − 2×%s − 2×%s − %d×%s ) ÷ %d = %s مم\n'
        'الحدّ = max( 1.5×%s , 40 ) = %s مم'
        % (_f(b, 0), _f(cover, 0), _f(db_tie, 0), nb_face, _f(db, 0),
           max(1, nb_face - 1), _f(clear, 1), _f(db, 0), _f(cl_min, 0)),
        '%s مم' % _f(clear, 1), '',
        'ACI 318-19 §25.2.3',
        'المسافة الصافية تضمن مرور الركام بين الأسياخ وتماسك الخرسانة بها. '
        'وهي أيضاً ما يحدّد عملياً أقصى عدد أسياخ يسعه المقطع.',
        'ok' if clear >= cl_min - 1e-6 else 'fail'))
    if phiPn and Pu:
        steps.append(step(
            5, 'كفاية المقطع للحمل المحوري',
            'φP_n ≥ P_u',
            'φP_n = %s kN  ≥  P_u = %s kN   →  نسبة الاستغلال = %s'
            % (_f(phiPn, 1), _f(Pu, 1), _f(Pu / phiPn, 3) if phiPn else '—'),
            _f(Pu / phiPn, 3) if phiPn else '—', '',
            'ACI 318-19 §22.4.2.1',
            'أقصى حمل محوري للعمود المطوَّق بأسوار: '
            'φP_n,max = 0.80·φ·[0.85·f′c·(A_g − A_st) + f_y·A_st] و φ = 0.65. '
            'معامل 0.80 يمثّل لامركزية صغيرة حتمية.',
            'ok' if Pu <= phiPn else 'fail'))
    return dict(title='الحديد الطولي للعمود', intro='', steps=steps,
                result=dict(rho=rho, Ag=Ag, Ast=Ast, n=n_bars, clear=clear,
                            nb_face=nb_face),
                refs=['ACI 318-19 §10.6.1.1 — حدود نسبة الحديد',
                      'ACI 318-19 §10.7.3.1 — أدنى عدد أسياخ',
                      'ACI 318-19 §25.2.3 — المسافة الصافية',
                      'ACI 318-19 §22.4.2.1 — أقصى حمل محوري'])


# ═══════════════════ ٥) عزم الجسر: من الحمل إلى العزم ═══════════════════
def beam_moment(w, L, kind='interior', method='coef', M=None, V=None,
                ln=None, face=None):
    """اشتقاق عزم الجسر — بمعاملات ACI التقريبية أو بالتحليل المصفوفي."""
    lnn = ln if ln else L
    steps = []
    steps.append(step(
        1, 'الحمل المُعامَل على الجسر',
        'w_u = 1.2·D + 1.6·L   (أو الحاكم من تراكيب §5.3.1)',
        'w_u = %s kN/m' % _f(w, 3),
        '%s kN/m' % _f(w, 3), '',
        'ACI 318-19 §5.3.1',
        'تراكيب الأحمال السبعة، والحاكم منها هو ما يُصمَّم عليه المقطع.',
        'info'))
    steps.append(step(
        2, 'البحر الصافي ℓn',
        'ℓn = L − ( c₁ + c₂ ) ÷ 2\nأي المسافة الصافية بين وجهَي الركيزتين',
        'ℓn = %s م' % _f(lnn, 3),
        '%s م' % _f(lnn, 3), '',
        'ACI 318-19 §6.5.4',
        'قوى التصميم تُحسب عند **وجه الركيزة** لا عند محورها، فالبحر '
        'المستعمل هو الصافي.', 'gov'))
    COEF = {
        'end_ext': (1.0 / 11.0, 'عزم موجب — بحر طرفي، الطرف الخارجي مبنيّ مع عمود'),
        'end_int': (1.0 / 14.0, 'عزم موجب — بحر طرفي'),
        'interior': (1.0 / 16.0, 'عزم موجب — بحر داخلي'),
        'neg_ext': (1.0 / 16.0, 'عزم سالب — وجه أول ركيزة داخلية (بحرين)'),
        'neg_int': (1.0 / 11.0, 'عزم سالب — وجه أول ركيزة داخلية'),
        'neg_far': (1.0 / 11.0, 'عزم سالب — وجوه بقية الركائز الداخلية'),
        'neg_col': (1.0 / 16.0, 'عزم سالب — عند عمود طرفي مبنيّ معه'),
    }
    c, lbl = COEF.get(kind, COEF['interior'])
    Mc = c * w * lnn * lnn
    steps.append(step(
        3, 'العزم بمعاملات الطريقة المبسّطة',
        'M = C · w_u · ℓn²\nو C معامل من جدول 6.5.2',
        'M = (1/%d) × %s × %s² = %s kN·m'
        % (round(1 / c), _f(w, 3), _f(lnn, 3), _f(Mc, 2)),
        '%s kN·m' % _f(Mc, 2), '',
        'ACI 318-19 جدول 6.5.2',
        '%s. وشروط استعمال الطريقة (§6.5.1): بحران فأكثر · البحور متقاربة '
        '(الأطول ÷ الأقصر ≤ 1.2) · حمل موزّع منتظم · الحمل الحي ≤ 3 أضعاف '
        'الميت · المقطع منشوري.' % lbl, 'ok'))
    if M is not None:
        steps.append(step(
            4, 'العزم من التحليل المصفوفي الفراغي',
            'حلّ {F} = [K]{u} للإطار كاملاً ثم M(x) من اتزان المقطع',
            'M = %s kN·m   (عند وجه الركيزة)' % _f(M, 2),
            '%s kN·m' % _f(M, 2), '',
            'تحليل مباشر',
            'الفرق عن المعاملات: التحليل يوزّع الحمل بخطوط 45° لا بشريحة '
            'كاملة، ويُشرك الأعمدة بمقاومة العزم. والمعاملات مقصودةٌ '
            'للجانب الآمن بلا تحليل.',
            'info'))
    return dict(title='اشتقاق عزم الجسر', intro='', steps=steps,
                result=dict(M_coef=Mc, coef=c, ln=lnn, w=w),
                refs=['ACI 318-19 §6.5.1 — شروط الطريقة المبسّطة',
                      'ACI 318-19 جدول 6.5.2 — معاملات العزم التقريبية',
                      'ACI 318-19 §6.5.4 — قوى التصميم عند وجه الركيزة'])


# ═══════════════════ ٦) حديد الجسر من العزم ═══════════════════
def beam_steel(b, h, d, Mu, fc, fy, cover=40.0, db=16.0, db_stir=10.0,
               As_used=None, n_bars=None, bw=None):
    """من العزم إلى عدد الأسياخ: ρ ثمّ As ثمّ العدد ثمّ التحقّق من φMn.

    b · h · d · cover بالمليمتر · Mu بالـ kN·m · fc · fy بالـ MPa.
    """
    steps = []
    Mn_ = Mu * 1e6                                        # N·mm
    bw = bw if bw else b                                  # عرض العصب (الساق)
    if abs(bw - b) > 1.0:
        steps.append(step(
            0, 'عرض الشفة الفعّال للمقطع T',
            'b_f = min( ℓn ÷ 4 ;  b_w + 16·h_f ;  s_beams )\ns_beams = المسافة بين مراكز الجسور',
            'b_w = %s مم  →  b_f = %s مم' % (_f(bw, 0), _f(b, 0)),
            '%s مم' % _f(b, 0), '',
            'ACI 318-19 §6.3.2.1',
            'البلاطة تعمل **شفةً ضاغطة** مع الجسر عند العزم الموجب، فيُحسب '
            'الانحناء على عرض الشفة الفعّال لا على عرض العصب. أمّا الحدّ '
            'الأدنى للحديد والقصّ فيُحسبان على b_w وحده.', 'info'))
    steps.append(step(
        1, 'العمق الفعّال d',
        'd = h − c − d_b,tie − d_b ÷ 2\nc = الغطاء الخرساني إلى وجه السوار',
        'd = %s − %s − %s − %s÷2 = %s مم'
        % (_f(h, 0), _f(cover, 0), _f(db_stir, 0), _f(db, 0), _f(d, 0)),
        '%s مم' % _f(d, 0), '',
        'ACI 318-19 §20.5.1.3',
        'الغطاء الخرساني للجسور المصبوبة داخل قوالب وغير معرّضة للتربة '
        'أو الجو 40 مم، ويُقاس إلى **وجه السوار** لا إلى السيخ الطولي.',
        'info'))

    Rn = Mn_ / (0.90 * b * d * d) if (b and d) else 0.0
    inner = 1.0 - 2.0 * Rn / (0.85 * fc)
    rho = (0.85 * fc / fy) * (1.0 - math.sqrt(max(0.0, inner))) if fc else 0.0
    As = rho * b * d
    steps.append(step(
        2, 'نسبة الحديد المطلوبة من العزم',
        'R_n = M_u ÷ ( φ · b · d² )\n'
        'ρ = ( 0.85·f′c ÷ f_y ) · [ 1 − √( 1 − 2·R_n ÷ (0.85·f′c) ) ]',
        'R_n = %s×10⁶ ÷ ( 0.90 × %s × %s² ) = %s MPa\n'
        'ρ = (0.85×%s ÷ %s) · [1 − √(1 − 2×%s ÷ (0.85×%s))] = %s'
        % (_f(Mu, 2), _f(b, 0), _f(d, 0), _f(Rn, 4),
           _f(fc, 0), _f(fy, 0), _f(Rn, 4), _f(fc, 0), _f(rho, 5)),
        '%s مم²' % _f(As, 0), '',
        'ACI 318-19 §22.2',
        'الاشتقاق من اتزان المقطع: كتلة الضغط المكافئة a = A_s·f_y ÷ (0.85·f′c·b) '
        'و M_n = A_s·f_y·(d − a/2) — و φ = 0.90 للمقطع المحكوم بالشدّ '
        '(جدول 21.2.2).', 'ok' if inner > 0 else 'fail'))

    As_min1 = 0.25 * math.sqrt(fc) / fy * bw * d
    As_min2 = 1.4 / fy * bw * d
    As_min = max(As_min1, As_min2)
    steps.append(step(
        3, 'أدنى حديد شدّ للجسر',
        'A_s,min = max( 0.25·√f′c ÷ f_y · b_w·d  ,  1.4 ÷ f_y · b_w·d )',
        'A_s,min = max( 0.25×√%s÷%s × %s×%s = %s , 1.4÷%s × %s×%s = %s ) = %s مم²'
        % (_f(fc, 0), _f(fy, 0), _f(bw, 0), _f(d, 0), _f(As_min1, 0),
           _f(fy, 0), _f(bw, 0), _f(d, 0), _f(As_min2, 0), _f(As_min, 0)),
        '%s مم²' % _f(As_min, 0), '',
        'ACI 318-19 §9.6.1.2',
        'الغرض أن تتجاوز مقاومة المقطع المسلَّح مقاومته **قبل التشقّق**، وإلّا '
        'انهار فجأةً لحظة أول شقّ. والحدّ الثاني 1.4/f_y يحكم عند '
        'f′c ≤ 31.4 MPa.', 'gov' if As_min > As else 'info'))

    As_req = max(As, As_min)
    Ab = math.pi * db * db / 4.0
    n_req = max(2, int(math.ceil(As_req / Ab))) if Ab else 0
    n_use = int(n_bars) if n_bars else n_req
    As_prov = As_used if As_used else n_use * Ab
    steps.append(step(
        4, 'عدد الأسياخ',
        'A_b = π·d_b² ÷ 4      ·      n = ⌈ A_s,req ÷ A_b ⌉\nولا يقلّ العدد عن سيخين',
        'A_b = π×%s²÷4 = %s مم²  →  n = ⌈%s ÷ %s⌉ = %d سيخ  →  A_s,prov = %s مم²'
        % (_f(db, 0), _f(Ab, 0), _f(As_req, 0), _f(Ab, 0), n_req, _f(As_prov, 0)),
        '%d Ø%s' % (n_use, _f(db, 0)), '',
        'ACI 318-19 §9.7.1',
        'سيخان على الأقل في كل وجه شدّ، ليكون للسوار ما يعلّق عليه زاويتاه.',
        'ok' if As_prov >= As_req - 1e-6 else 'fail'))

    a = As_prov * fy / (0.85 * fc * b) if (fc and b) else 0.0
    phiMn = 0.90 * As_prov * fy * (d - a / 2.0) / 1e6
    steps.append(step(
        5, 'التحقّق: مقاومة المقطع المنفَّذ',
        'a = A_s·f_y ÷ ( 0.85·f′c·b )\n'
        'φM_n = φ · A_s · f_y · ( d − a ÷ 2 )      ويجب  φM_n ≥ M_u',
        'a = %s×%s ÷ (0.85×%s×%s) = %s مم\n'
        'φM_n = 0.90 × %s × %s × (%s − %s÷2) = %s kN·m   مقابل  M_u = %s kN·m'
        % (_f(As_prov, 0), _f(fy, 0), _f(fc, 0), _f(b, 0), _f(a, 1),
           _f(As_prov, 0), _f(fy, 0), _f(d, 0), _f(a, 1), _f(phiMn, 2), _f(Mu, 2)),
        'φM_n = %s kN·m  ·  M_u/φM_n = %s'
        % (_f(phiMn, 2), _f(Mu / phiMn, 3) if phiMn else '—'), '',
        'ACI 318-19 §22.2 · جدول 21.2.2',
        'φ = 0.90 مشروط بأن يكون المقطع محكوماً بالشدّ، أي انفعال الحديد '
        'الأقصى ε_t ≥ 0.005 عند الانهيار. وهذا ما يضمنه الحدّ الأعلى للنسبة.',
        'ok' if phiMn >= Mu - 1e-9 else 'fail'))

    return dict(title='حديد الانحناء للجسر — من العزم إلى العدد',
                intro='العزم وحده لا يكفي: الطريق منه إلى «٥Ø16» يمرّ بأربع '
                      'خطوات، كلٌّ منها ببندٍ يحدّها.',
                steps=renumber(steps),
                result=dict(As=As, As_min=As_min, As_req=As_req, n=n_use,
                            As_prov=As_prov, a=a, phiMn=phiMn, rho=rho),
                refs=['ACI 318-19 §22.2 — مقاومة الانحناء الاسمية',
                      'ACI 318-19 §9.6.1.2 — أدنى حديد شدّ',
                      'ACI 318-19 جدول 21.2.2 — معامل التخفيض φ',
                      'ACI 318-19 §20.5.1.3 — الغطاء الخرساني'])


# ═══════════════════ ٧) الأساس المنفرد — الاشتقاق الكامل ═══════════════════
def footing(p):
    """اشتقاق تصميم الأساس المنفرد كاملاً وفق ACI 318-19.

    الأبعاد **تُستلَم** كما حُسبت (B و h)، ثمّ يُعاد اشتقاق كل فحص عليها
    من أوّله بالمعادلة والتعويض. فلا نسختان تتباعدان: النسخة الحاسبة تُعطي
    البُعد، وهذه تُظهر لماذا خرج هكذا وأين يقف من كل حدّ.

    p = {Ps, Pu, B, h, c1, c2, fc, fy, qa, q_net, cover, db, Mux, Muy, As, gamma}
        Ps·Pu بالـ kN · B بالمتر · h·c1·c2·cover·db بالمليمتر · qa·q_net بالـ kPa
    """
    g = lambda k, dflt=0.0: float(p.get(k) if p.get(k) is not None else dflt)
    Ps, Pu = g('Ps'), g('Pu')
    B = g('B')                                            # م
    Bmm = B * 1000.0
    h = g('h', 300.0)
    c1, c2 = g('c1', 300.0), g('c2', 300.0)
    fc, fy = g('fc', 25.0), g('fy', 420.0)
    qa = g('qa', 150.0)
    cov = g('cover', 75.0)
    db = g('db', 12.0)
    e_x, e_y = g('Mux'), g('Muy')
    phiV, phiM, phiB = 0.75, 0.90, 0.65                   # جدول 21.2.1
    steps = []

    # ---- (١) ضغط التربة الصافي المسموح ----
    q_net = g('q_net', qa)
    steps.append(step(
        1, 'ضغط التربة الصافي المسموح',
        'q_net = q_a − γ_c·h_f − γ_s·( D_f − h_f )\nγ_c = وزن الخرسانة   ·   γ_s = وزن الردم   ·   D_f = عمق التأسيس',
        'q_net = %s − %s = %s kPa          (المطروح = وزن الأساس والردم فوقه)'
        % (_f(qa, 0), _f(qa - q_net, 1), _f(q_net, 1)),
        '%s kPa' % _f(q_net, 1), '',
        'ACI 318-19 §13.3.1.1',
        'مساحة الأساس تُحدَّد بأحمال **الخدمة** غير المُعامَلة وبضغط التربة '
        'المسموح، لأن هبوط التربة ظاهرة خدمة لا حالة انهيار. ويُخصم من '
        'المسموح وزن الأساس نفسه والردم فوقه لأنهما يستهلكان منه.', 'info'))

    # ---- (٢) المساحة والبُعد ----
    A_req = Ps / q_net if q_net else 0.0
    A_act = B * B
    steps.append(step(
        2, 'المساحة المطلوبة والبُعد',
        'A_req = P_s ÷ q_net      ·      B = √A\nويُقرَّب B لأعلى إلى أقرب 50 مم',
        'A = %s ÷ %s = %s م²   →   B = √%s = %s م   →   المعتمَد B = %s م '
        '(A = %s م²)'
        % (_f(Ps, 1), _f(q_net, 1), _f(A_req, 3), _f(A_req, 3),
           _f(math.sqrt(A_req) if A_req > 0 else 0, 3), _f(B, 2), _f(A_act, 3)),
        '%s × %s م' % (_f(B, 2), _f(B, 2)), '',
        'ACI 318-19 §13.3.1.1',
        'التقريب لأعلى لا لأدنى: أيّ نقصٍ بالمساحة يرفع الضغط فوق المسموح. '
        'والأساس مربّع لأن العمود مركزيّ والعزوم متقاربة بالاتجاهين.',
        'ok' if A_act >= A_req - 1e-9 else 'fail'))

    # ---- (٣) اللامركزية وضغط التربة الفعلي ----
    Msvc = math.sqrt(e_x * e_x + e_y * e_y)
    ecc = (Msvc / Ps) if Ps else 0.0
    q_max = (Ps / A_act) * (1 + 6 * ecc / B) if A_act and B else 0.0
    q_min = (Ps / A_act) * (1 - 6 * ecc / B) if A_act and B else 0.0
    kern = B / 6.0
    steps.append(step(
        3, 'ضغط التربة الفعلي مع اللامركزية',
        'e = M ÷ P      ·      q = ( P ÷ A ) · ( 1 ± 6·e ÷ B )\n'
        'وتبقى القاعدة كلّها بالضغط ما دام  e ≤ B ÷ 6  (حدّ النواة)',
        'e = %s ÷ %s = %s م   ·   B÷6 = %s م\n'
        'q_max = (%s ÷ %s)·(1 + 6×%s ÷ %s) = %s kPa   مقابل المسموح %s kPa\n'
        'q_min = %s kPa'
        % (_f(Msvc, 1), _f(Ps, 1), _f(ecc, 4), _f(kern, 3),
           _f(Ps, 1), _f(A_act, 3), _f(ecc, 4), _f(B, 2), _f(q_max, 1), _f(qa, 0),
           _f(q_min, 1)),
        '%s / %s kPa' % (_f(q_max, 1), _f(qa, 0)), '',
        'ACI 318-19 §13.3.1.1',
        'خارج النواة (e > B/6) ينفصل جزء من القاعدة عن التربة فلا يحمل شيئاً، '
        'ويتركّز الضغط على الباقي فيقفز فوق المسموح — ولذلك يُكبَّر البُعد '
        'حتى يعود e داخل النواة.',
        'ok' if (q_max <= qa * 1.001 and ecc <= kern) else 'fail'))

    # ---- (٤) ضغط التربة المُعامَل ----
    qu = Pu / A_act if A_act else 0.0                     # kPa
    quN = qu / 1000.0                                     # N/mm²
    steps.append(step(
        4, 'ضغط التربة المُعامَل (للتصميم)',
        'q_u = P_u ÷ A\nولا يُخصم منه وزن الأساس ولا الردم',
        'q_u = %s ÷ %s = %s kPa = %s N/مم²'
        % (_f(Pu, 1), _f(A_act, 3), _f(qu, 1), _f(quN, 5)),
        '%s kPa' % _f(qu, 1), '',
        'ACI 318-19 §13.3.1.2',
        'وزن الأساس والردم لا يُخصمان هنا لأنهما يعملان **لأسفل** بمقدار ما '
        'تدفع التربة لأعلى تحتهما تماماً، فلا ينتج عنهما قصّ ولا عزم في '
        'القاعدة. والحمل المُعامَل للتصميم الإنشائي وحده.', 'info'))

    # ---- (٥) العمق الفعّال ----
    # يُستلَم كما حُسب إن أُرسل، فلا يختلف رقمٌ هنا عن رقمٍ هناك بقطر سيخ.
    db_d = g('db_d', db)
    d = g('d', h - cov - db_d)
    steps.append(step(
        5, 'العمق الفعّال d',
        'd = h − c − d_b\nc = الغطاء الخرساني   ·   d_b = قطر سيخ الشبكة',
        'd = %s − %s − %s = %s مم' % (_f(h, 0), _f(cov, 0), _f(h - cov - d, 0),
                                      _f(d, 0)),
        '%s مم' % _f(d, 0), '',
        'ACI 318-19 §20.5.1.3',
        'الغطاء 75 مم للخرسانة **المصبوبة مباشرةً على التربة** ودائمةِ '
        'التماسّ بها — وهو أكبر غطاء بالكود، لأن سطح التربة غير منتظم '
        'والصبّ عليه يبتلع جزءاً من الغطاء.', 'info'))

    # ---- (٦) الانحناء عند وجه العمود ----
    lc = (Bmm - c1) / 2.0
    Mu = quN * Bmm * lc * lc / 2.0                        # N·mm
    steps.append(step(
        6, 'عزم الانحناء عند وجه العمود',
        'ℓ = ( B − c₁ ) ÷ 2        (ذراع الكابولي)\n'
        'M_u = q_u · B · ℓ² ÷ 2',
        'ℓ = (%s − %s) ÷ 2 = %s مم = %s م\n'
        'M_u = %s × %s × %s² ÷ 2 = %s kN·m'
        % (_f(Bmm, 0), _f(c1, 0), _f(lc, 0), _f(lc / 1000.0, 3),
           _f(quN, 5), _f(Bmm, 0), _f(lc, 0), _f(Mu / 1e6, 2)),
        '%s kN·m' % _f(Mu / 1e6, 2), '',
        'ACI 318-19 §13.3.2.1',
        'المقطع الحرج للانحناء عند **وجه العمود** بالضبط، لأن الأساس يعمل '
        'كابولياً يخرج من العمود، وأقصى عزم عند جذر الكابول. '
        '(ولو كان العمود على قاعدة فولاذية لانتقل المقطع إلى منتصف المسافة '
        'بين وجه العمود وحافة القاعدة — §13.3.2.1.)', 'gov'))

    Rn = Mu / (phiM * Bmm * d * d) if (Bmm and d) else 0.0
    inner = 1.0 - 2.0 * Rn / (0.85 * fc)
    rho = (0.85 * fc / fy) * (1.0 - math.sqrt(max(0.0, inner)))
    As = rho * Bmm * d
    steps.append(step(
        7, 'الحديد المطلوب للانحناء',
        'R_n = M_u ÷ ( φ·b·d² )   ·   ρ = (0.85f′c ÷ f_y)[1 − √(1 − 2R_n ÷ 0.85f′c)]\n'
        'A_s = ρ · b · d\nو b = B  أي عرض الأساس كاملاً',
        'R_n = %s×10⁶ ÷ (0.90 × %s × %s²) = %s MPa  →  ρ = %s\n'
        'A_s = %s × %s × %s = %s مم²'
        % (_f(Mu / 1e6, 2), _f(Bmm, 0), _f(d, 0), _f(Rn, 4), _f(rho, 5),
           _f(rho, 5), _f(Bmm, 0), _f(d, 0), _f(As, 0)),
        '%s مم²' % _f(As, 0), '',
        'ACI 318-19 §22.2 · جدول 21.2.2',
        'φ = 0.90 للانحناء المحكوم بالشدّ. والعرض المستعمل هو البُعد الكامل '
        'B لأن الشريحة المقطوعة تمتدّ على عرض الأساس كلّه.', 'ok'))

    As_min = 0.0018 * Bmm * h
    steps.append(step(
        8, 'أدنى حديد للأساس',
        'A_s,min = 0.0018 · b · h        (نسبة الانكماش والحرارة)',
        'A_s,min = 0.0018 × %s × %s = %s مم²   مقابل المطلوب للانحناء %s مم²'
        % (_f(Bmm, 0), _f(h, 0), _f(As_min, 0), _f(As, 0)),
        '%s مم²' % _f(As_min, 0), '',
        'ACI 318-19 §13.3.2.3 · جدول 24.4.3.2',
        'الأساس يأخذ حدّه الأدنى من حديد **الانكماش والحرارة** للبلاطات '
        '(0.0018 عند f_y = 420 MPa) لا من حدّ الجسور 1.4/f_y — لأنه بلاطة '
        'عريضة لا عنصر انحناء نحيل. وهذا الحدّ يحكم غالباً في الأسس '
        'القليلة العمق.', 'gov' if As_min > As else 'info'))

    As_use = max(As, As_min)
    Ab = math.pi * db * db / 4.0
    n_bar = max(4, int(math.ceil(As_use / Ab))) if Ab else 0
    s_bar = (Bmm - 2 * cov) / (n_bar - 1) if n_bar > 1 else 0.0
    s_lim = min(3 * h, 450.0)
    steps.append(step(
        9, 'عدد الأسياخ وتباعدها بالاتجاهين',
        'n = ⌈ A_s ÷ A_b ⌉      ·      s = ( B − 2c ) ÷ ( n − 1 )\n'
        'ويجب:  s ≤ min( 3·h , 450 مم )',
        'n = ⌈%s ÷ %s⌉ = %d سيخ Ø%s  →  s = (%s − 2×%s) ÷ %d = %s مم\n'
        'الحدّ = min(3×%s , 450) = %s مم%s'
        % (_f(As_use, 0), _f(Ab, 0), n_bar, _f(db, 0), _f(Bmm, 0), _f(cov, 0),
           n_bar - 1, _f(s_bar, 0), _f(h, 0), _f(s_lim, 0),
           ('\nالمنفَّذ بالموقع: %s مم (يُقرَّب لأدنى رقمٍ عمليّ فيزيد العدد لا ينقص)'
            % _f(g('s_exec'), 0)) if p.get('s_exec') else ''),
        '%d Ø%s @ %s مم' % (n_bar, _f(db, 0), _f(g('s_exec', s_bar), 0)),
        '(بالاتجاهين)',
        'ACI 318-19 §8.7.2.2',
        'الأساس المربّع يُوزَّع حديده بانتظام بالاتجاهين. '
        '(ولو كان مستطيلاً لتركّز جزء من حديد الاتجاه القصير في شريط عرضه '
        'يساوي البُعد القصير — §13.3.3.3.)',
        'ok' if s_bar <= s_lim + 1e-6 else 'fail'))

    # ---- (٧) معاملا نسخة 2019 ----
    lam_s = min(1.0, math.sqrt(2.0 / (1.0 + d / 250.0)))
    rho_w = min(0.02, As_use / (Bmm * d)) if (Bmm and d) else 0.0
    steps.append(step(
        10, 'معاملا نسخة 2019: أثر الحجم λs ونسبة التسليح ρw',
        'λ_s = √( 2 ÷ ( 1 + d ÷ 250 ) )  ≤  1.0        ·        ρ_w = A_s ÷ ( b·d )',
        'λ_s = √(2 ÷ (1 + %s÷250)) = %s\nρ_w = %s ÷ (%s × %s) = %s'
        % (_f(d, 0), _f(lam_s, 4), _f(As_use, 0), _f(Bmm, 0), _f(d, 0),
           _f(rho_w, 5)),
        'λ_s = %s   ·   ρ_w = %s' % (_f(lam_s, 4), _f(rho_w, 5)), '',
        'ACI 318-19 §22.5.5.1.3 · جدول 22.5.5.1',
        'هذان المعاملان **أضافتهما نسخة 2019 ولم يكونا في 318-14**: التجارب '
        'أظهرت أن المقاطع السميكة بلا أساور قصّ تنهار بإجهاد أقلّ (أثر '
        'الحجم)، وأن المقطع قليل التسليح مقاومته للقصّ أدنى لأن الشقّ ينفتح '
        'أوسع فيضعف التعشيق الركامي. والأساس **قليل التسليح بطبعه**، فمقاومته '
        'بنسخة 2019 تنزل إلى نحو نصف ما كانت تعطيه 2014 — وهذا بالضبط سبب '
        'زيادة سماكة الأسس عندنا.',
        'gov' if lam_s < 0.999 else 'info'))

    # ---- (٨) القصّ الثاقب ----
    beta = max(c1, c2) / min(c1, c2)
    alpha_s = 40.0
    bo = 2 * (c1 + d) + 2 * (c2 + d)
    Ap = (c1 + d) * (c2 + d)
    Vu2 = quN * (Bmm * Bmm - Ap)
    vu2 = Vu2 / (bo * d) if (bo and d) else 0.0
    v1 = 0.33 * math.sqrt(fc)
    v2 = 0.17 * (1 + 2.0 / beta) * math.sqrt(fc)
    v3 = 0.083 * (2 + alpha_s * d / bo) * math.sqrt(fc) if bo else 0.0
    vc2 = lam_s * min(v1, v2, v3)
    gov2 = ('0.33√f′c' if min(v1, v2, v3) == v1 else
            ('0.17(1 + 2/β)√f′c' if min(v1, v2, v3) == v2 else
             '0.083(2 + αs·d/b₀)√f′c'))
    steps.append(step(
        11, 'القصّ الثاقب (ثنائي الاتجاه)',
        'b₀ = 2(c₁ + d) + 2(c₂ + d)          (المحيط الحرج على d÷2 من وجه العمود)\n'
        'V_u = q_u · ( B² − (c₁+d)(c₂+d) )   ·   v_u = V_u ÷ ( b₀ · d )\n'
        'v_c = λ_s · min [ 0.33√f′c ; 0.17(1 + 2/β)√f′c ; 0.083(2 + α_s·d/b₀)√f′c ]',
        'b₀ = 2(%s+%s) + 2(%s+%s) = %s مم   ·   β = %s ÷ %s = %s   ·   α_s = 40\n'
        'V_u = %s × (%s² − %s) = %s kN   →   v_u = %s MPa\n'
        'v_c = %s × min[ %s ; %s ; %s ] = %s MPa   →   φv_c = %s MPa'
        % (_f(c1, 0), _f(d, 0), _f(c2, 0), _f(d, 0), _f(bo, 0),
           _f(max(c1, c2), 0), _f(min(c1, c2), 0), _f(beta, 3),
           _f(quN, 5), _f(Bmm, 0), _f(Ap, 0), _f(Vu2 / 1000.0, 1), _f(vu2, 3),
           _f(lam_s, 4), _f(v1, 3), _f(v2, 3), _f(v3, 3), _f(vc2, 3),
           _f(phiV * vc2, 3)),
        'v_u = %s ≤ φv_c = %s MPa' % (_f(vu2, 3), _f(phiV * vc2, 3)), '',
        'ACI 318-19 جدول 22.6.5.2',
        'الحاكم هنا هو **%s**. و α_s = 40 للعمود «الداخلي» بمعنى الكود: '
        'المحيط الحرج مغلق من جهاته الأربع. والأساس المنفرد عمودُه في وسطه، '
        'فمحيطه مغلق دائماً مهما كان موقع العمود بالمبنى — وقِيَم 30 و20 '
        'تخصّ عموداً عند حافّة بلاطة أو ركنها حيث يُبتر المحيط. '
        'و β = نسبة البُعد الأطول للعمود إلى الأقصر: كلّما استطال العمود '
        'تركّز القصّ على طرفَي المحيط فنزلت المقاومة.'
        % gov2, 'ok' if vu2 <= phiV * vc2 else 'fail'))

    # ---- (٩) القصّ أحادي الاتجاه ----
    l_ov = (Bmm - c1) / 2.0
    Vu1 = quN * Bmm * max(0.0, l_ov - d)
    vc1a = 0.66 * lam_s * (rho_w ** (1.0 / 3.0)) * math.sqrt(fc) if rho_w > 0 else 0.0
    vc1b = 0.42 * math.sqrt(fc)
    vc1 = min(vc1a, vc1b)
    Vc1 = vc1 * Bmm * d
    steps.append(step(
        12, 'القصّ أحادي الاتجاه (بلا أساور قصّ)',
        'المقطع الحرج على مسافة d من وجه العمود:\n'
        'V_u = q_u · B · ( ℓ − d )\n'
        'V_c = 0.66 · λ_s · λ · ρ_w^⅓ · √f′c · b · d\nبحدّ أعلى:  V_c ≤ 0.42 · λ · √f′c · b · d',
        'V_u = %s × %s × (%s − %s) = %s kN\n'
        'v_c = min( 0.66×%s×%s^⅓×√%s = %s ; 0.42×√%s = %s ) = %s MPa\n'
        'φV_c = 0.75 × %s × %s × %s = %s kN'
        % (_f(quN, 5), _f(Bmm, 0), _f(l_ov, 0), _f(d, 0), _f(Vu1 / 1000.0, 1),
           _f(lam_s, 4), _f(rho_w, 5), _f(fc, 0), _f(vc1a, 3),
           _f(fc, 0), _f(vc1b, 3), _f(vc1, 3),
           _f(vc1, 3), _f(Bmm, 0), _f(d, 0), _f(phiV * Vc1 / 1000.0, 1)),
        'V_u = %s ≤ φV_c = %s kN'
        % (_f(Vu1 / 1000.0, 1), _f(phiV * Vc1 / 1000.0, 1)), '',
        'ACI 318-19 جدول 22.5.5.1 (الحالة A_v < A_v,min)',
        'الأساس بلا أساور قصّ، فيقع في حالة الجدول التي تدخلها ρ_w. '
        'والسقف 0.42·λ·√f′c من §22.5.5.1.1 يمنع المبالغة عند التسليح العالي. '
        'ولو رسب هذا الفحص فالعلاج **زيادة السماكة** لا إضافة أساور، لأن '
        'أساور القصّ في الأسس غير عملية.',
        'ok' if Vu1 <= phiV * Vc1 else 'fail'))

    # ---- (١٠) التحمّل عند وجه العمود ----
    A1 = c1 * c2
    A2 = min(Bmm * Bmm, (c1 + 4.0 * h) * (c2 + 4.0 * h))   # انتشار 2:1
    ratio = min(2.0, math.sqrt(A2 / A1)) if A1 else 1.0
    Bn = 0.85 * fc * A1 * ratio
    steps.append(step(
        13, 'تحمّل الخرسانة عند وجه العمود',
        'φB_n = φ · 0.85 · f′c · A₁ · √( A₂ ÷ A₁ )\nبحدّ:  √( A₂ ÷ A₁ ) ≤ 2',
        '√(A₂÷A₁) = √(%s ÷ %s) = %s  (بحدّ 2)\n'
        'φB_n = 0.65 × 0.85 × %s × %s × %s = %s kN   مقابل P_u = %s kN'
        % (_f(A2, 0), _f(A1, 0), _f(ratio, 3), _f(fc, 0), _f(A1, 0), _f(ratio, 3),
           _f(phiB * Bn / 1000.0, 1), _f(Pu, 1)),
        '%s kN' % _f(phiB * Bn / 1000.0, 1), '',
        'ACI 318-19 §22.8.3.2',
        'الأساس أعرض من العمود، فالخرسانة المحيطة تحصر منطقة التحميل '
        'وترفع تحمّلها بجذر نسبة المساحتين — بحدّ الضعف. و A₂ هي قاعدة '
        'الهرم المرسوم بميل 1 أفقي إلى 2 رأسي من محيط العمود.',
        'ok' if Pu <= phiB * Bn / 1000.0 else 'fail'))

    As_dow = 0.005 * A1
    steps.append(step(
        14, 'أشاير الربط (Dowels) بين العمود والأساس',
        'A_s,dowel ≥ 0.005 · A_g   (A_g للعمود)',
        'A_s = 0.005 × %s × %s = %s مم²   (ولا تقلّ عن 4 أسياخ)'
        % (_f(c1, 0), _f(c2, 0), _f(As_dow, 0)),
        '%s مم²' % _f(As_dow, 0), '',
        'ACI 318-19 §16.3.4.1',
        'حتى لو مرّ فحص التحمّل بلا حاجة، يبقى الحدّ الأدنى للأشاير واجباً '
        'لنقل القصّ الأفقي ومنع انزلاق العمود عن قاعدته.', 'info'))

    # ---- (١١) طول النشر المتاح ----
    ld = 0.0
    try:
        import engine as _E
        ld = _E.dev_length(db, fc, fy, cover=cov, spacing=s_bar)
    except Exception:                                      # noqa: BLE001
        ld = max(300.0, fy * db / (2.1 * math.sqrt(fc)))
    l_av = l_ov - cov
    steps.append(step(
        15, 'طول النشر المتاح لحديد الأساس',
        'ℓ_avail = ( B − c₁ ) ÷ 2 − c\nويجب:  ℓ_avail ≥ ℓ_d',
        'ℓ_avail = %s − %s = %s مم   ·   ℓ_d = %s مم'
        % (_f(l_ov, 0), _f(cov, 0), _f(l_av, 0), _f(ld, 0)),
        '%s مقابل %s مم' % (_f(l_av, 0), _f(ld, 0)), '',
        'ACI 318-19 §13.3.2.2 · المعادلة 25.4.2.4(a)',
        'السيخ يجب أن يجد بعد المقطع الحرج طولاً يكفي لنشر إجهاده كاملاً، '
        'وإلّا انسلّ من الخرسانة قبل أن يخضع. وإن قصُر المتاح فالعلاج '
        'عكف السيخ لأعلى عند الحافة.',
        'ok' if l_av >= ld - 1e-6 else 'warn'))

    ok = (q_max <= qa * 1.001 and vu2 <= phiV * vc2 and Vu1 <= phiV * Vc1)
    return dict(
        title='الأساس المنفرد — الاشتقاق الكامل وفق ACI 318-19',
        intro='الأساس يُصمَّم مرّتين: مقاسه بأحمال <b>الخدمة</b> وضغط التربة '
              'المسموح، وسماكته وحديده بأحمال <b>مُعامَلة</b> وفحصَي قصّ '
              'وانحناء. وكل رقم أدناه ببنده.',
        steps=renumber(steps),
        result=dict(B=B, h=h, d=d, qu=qu, q_max=q_max, e=ecc, Mu=Mu / 1e6,
                    As=As, As_min=As_min, As_use=As_use, n_bar=n_bar,
                    s_bar=s_bar, lam_s=lam_s, rho_w=rho_w, bo=bo, vu2=vu2,
                    phi_vc2=phiV * vc2, Vu1=Vu1 / 1000.0,
                    phi_Vc1=phiV * Vc1 / 1000.0, ld=ld, ok=ok),
        refs=['ACI 318-19 §13.3.1.1 — المقاس بأحمال الخدمة',
              'ACI 318-19 §13.3.2.1 — المقطع الحرج للانحناء عند وجه العمود',
              'ACI 318-19 جدول 22.5.5.1 · §22.5.5.1.3 — القصّ الأحادي و λs',
              'ACI 318-19 جدول 22.6.5.2 — القصّ الثاقب',
              'ACI 318-19 §22.8.3.2 — التحمّل · §16.3.4.1 — الأشاير',
              'ACI 318-19 §20.5.1.3 — الغطاء 75 مم صبّاً على التربة',
              'ACI 318-19 جدول 24.4.3.2 — أدنى حديد 0.0018'])


# ═══════════════════ ٨) الحصيرة (Raft) — الاشتقاق الكامل ═══════════════════
def raft(p):
    """اشتقاق تصميم الحصيرة وفق ACI 318-19.

    الحصيرة بلاطةٌ واحدة تحمل المبنى كلّه، فمنطق تصميمها يختلف عن الأساس
    المنفرد: مساحتها **مفروضة** بمسقط المبنى لا محسوبة، والحاكم فيها القصّ
    الثاقب تحت أثقل عمود ثم عزوم الشرائح بين الأعمدة.

    p = {total, Pmax, Lx, Ly, h, d, q_serv, q_u, qa, cx, cy, span, fc, fy,
         cover, top, bottom, As_min}
    """
    g = lambda k, dflt=0.0: float(p.get(k) if p.get(k) is not None else dflt)
    Lx, Ly = g('Lx'), g('Ly')
    A = Lx * Ly
    total, Pmax = g('total'), g('Pmax')
    h, cov = g('h', 400.0), g('cover', 75.0)
    d = g('d', h - cov - 20.0)
    cx, cy = g('cx', 400.0), g('cy', 500.0)
    fc, fy, qa = g('fc', 25.0), g('fy', 420.0), g('qa', 150.0)
    span = g('span', 5.0)
    q_serv = g('q_serv', total / A if A else 0.0)
    q_u = g('q_u', 1.45 * q_serv)
    phiV = 0.75
    steps = []

    steps.append(step(
        1, 'ضغط التربة تحت الحصيرة',
        'q_s = ΣP_service ÷ A_raft\nويجب:  q_s ≤ q_a',
        'A = %s × %s = %s م²\nq = %s ÷ %s = %s kPa   مقابل المسموح %s kPa'
        % (_f(Lx, 2), _f(Ly, 2), _f(A, 1), _f(total, 0), _f(A, 1),
           _f(q_serv, 2), _f(qa, 0)),
        '%s / %s kPa' % (_f(q_serv, 1), _f(qa, 0)), '',
        'ACI 318-19 §13.3.1.1',
        'مساحة الحصيرة **مفروضة** بمسقط المبنى لا محسوبة، فالفحص هنا عكسيّ: '
        'هل يكفي هذا المسقط؟ ولهذا تُختار الحصيرة أصلاً حين تتجاوز مساحة '
        'الأسس المنفردة نحو نصف مساحة المبنى — عندها صبّها لوحاً واحداً '
        'أرخص وأضبط للهبوط التفاضلي.',
        'ok' if q_serv <= qa * 1.001 else 'fail'))

    steps.append(step(
        2, 'العمق الفعّال',
        'd = h − c − d_b\nc = الغطاء الخرساني   ·   d_b = قطر سيخ الشبكة',
        'd = %s − %s − %s = %s مم' % (_f(h, 0), _f(cov, 0), _f(h - cov - d, 0),
                                      _f(d, 0)),
        '%s مم' % _f(d, 0), '',
        'ACI 318-19 §20.5.1.3',
        'الغطاء 75 مم لأن الوجه السفلي مصبوب مباشرةً على التربة.', 'info'))

    lam_s = min(1.0, math.sqrt(2.0 / (1.0 + d / 250.0)))
    beta = max(cx, cy) / min(cx, cy)
    bo = 2 * (cx + d) + 2 * (cy + d)
    v1 = 0.33 * math.sqrt(fc)
    v2 = 0.17 * (1 + 2.0 / beta) * math.sqrt(fc)
    v3 = 0.083 * (2 + 40.0 * d / bo) * math.sqrt(fc) if bo else 0.0
    vc = lam_s * min(v1, v2, v3)
    phiVc = phiV * vc * bo * d / 1000.0
    Vu = Pmax - q_u * (cx + d) * (cy + d) / 1e6
    gov = ('0.33√f′c' if min(v1, v2, v3) == v1 else
           ('0.17(1 + 2/β)√f′c' if min(v1, v2, v3) == v2 else
            '0.083(2 + α_s·d/b₀)√f′c'))
    steps.append(step(
        3, 'معامل أثر الحجم λs',
        'λ_s = √( 2 ÷ ( 1 + d ÷ 250 ) )   ≤ 1.0',
        'λ_s = √(2 ÷ (1 + %s÷250)) = %s' % (_f(d, 0), _f(lam_s, 4)),
        _f(lam_s, 4), '',
        'ACI 318-19 §22.5.5.1.3',
        'الحصيرة **سميكة بطبعها**، وأثر الحجم يشتدّ كلّما عمُق المقطع: '
        'عند d = 430 مم ينزل λ_s إلى نحو 0.86، أي أن نسخة 2019 تخصم %s٪ من '
        'مقاومة القصّ التي كانت تعطيها 2014 لهذا المقطع نفسه.'
        % _f((1 - lam_s) * 100, 0),
        'gov' if lam_s < 0.999 else 'info'))

    steps.append(step(
        4, 'القصّ الثاقب تحت أثقل عمود — وهو الحاكم للسماكة',
        'b₀ = 2(c₁ + d) + 2(c₂ + d)\n'
        'V_u = P_u − q_u · (c₁ + d)(c₂ + d)\n'
        'v_c = λ_s · min [ 0.33√f′c ; 0.17(1 + 2/β)√f′c ; 0.083(2 + α_s·d/b₀)√f′c ]',
        'b₀ = 2(%s+%s) + 2(%s+%s) = %s مم  ·  β = %s  ·  α_s = 40\n'
        'V_u = %s − %s×(%s×%s)/10⁶ = %s kN\n'
        'v_c = %s × min[ %s ; %s ; %s ] = %s MPa\n'
        'φV_c = 0.75 × %s × %s × %s ÷ 1000 = %s kN'
        % (_f(cx, 0), _f(d, 0), _f(cy, 0), _f(d, 0), _f(bo, 0), _f(beta, 3),
           _f(Pmax, 0), _f(q_u, 1), _f(cx + d, 0), _f(cy + d, 0), _f(Vu, 1),
           _f(lam_s, 4), _f(v1, 3), _f(v2, 3), _f(v3, 3), _f(vc, 3),
           _f(vc, 3), _f(bo, 0), _f(d, 0), _f(phiVc, 1)),
        'V_u = %s ≤ φV_c = %s kN' % (_f(Vu, 1), _f(phiVc, 1)), '',
        'ACI 318-19 جدول 22.6.5.2',
        'الحاكم هنا **%s**. والقصّ الثاقب هو ما يقرّر سماكة الحصيرة: تُزاد '
        'السماكة 25 مم كل دورة حتى يمرّ هذا الفحص وحده. ولو عاند الفحص '
        'فالبدائل: تغليظ موضعي تحت العمود (Drop Panel) أو رؤوس قصّ فولاذية '
        '(§22.6.4.2) أو تكبير مقطع العمود — لا أساور، فهي غير عملية هنا.'
        % gov,
        'gov' if Vu <= phiVc else 'fail'))

    Mt, Mb = q_u * span ** 2 / 10.0, q_u * span ** 2 / 12.0
    steps.append(step(
        5, 'عزوم الشرائح بين الأعمدة',
        'العلوي (فوق الأعمدة):  M = q_u · L² ÷ 10\n'
        'السفلي (وسط البحور):   M = q_u · L² ÷ 12',
        'L = %s م  ·  q_u = %s kPa\n'
        'M_top = %s × %s² ÷ 10 = %s kN·م/م\n'
        'M_bot = %s × %s² ÷ 12 = %s kN·م/م'
        % (_f(span, 2), _f(q_u, 1), _f(q_u, 1), _f(span, 2), _f(Mt, 1),
           _f(q_u, 1), _f(span, 2), _f(Mb, 1)),
        '%s / %s kN·م/م' % (_f(Mt, 1), _f(Mb, 1)), '',
        'ACI 318-19 §6.5.2 · §13.3.4',
        'الحصيرة **بلاطةٌ مقلوبة**: التربة تدفعها لأعلى والأعمدة تشدّها '
        'لأسفل، فالشدّ فوق الأعمدة (حديد علوي) وفي وسط البحور تحت (حديد '
        'سفلي) — عكس السقف تماماً. والمعاملان 1/10 و1/12 من الطريقة '
        'المبسّطة للبلاطات المستمرة.', 'ok'))

    As_min = 0.0018 * 1000.0 * h
    steps.append(step(
        6, 'أدنى حديد للحصيرة',
        'A_s,min = 0.0018 · b · h\nلكل متر عرض — وبالوجهين والاتجاهين',
        'A_s,min = 0.0018 × 1000 × %s = %s مم²/م' % (_f(h, 0), _f(As_min, 0)),
        '%s مم²/م' % _f(As_min, 0), '',
        'ACI 318-19 جدول 24.4.3.2 · §13.3.4.3',
        'الحصيرة بلاطة عريضة، فحدّها الأدنى نسبة الانكماش والحرارة 0.0018 '
        'عند f_y = 420 MPa — **بالوجهين وبالاتجاهين الأربعة**، لأن التشقّق '
        'الحراري في لوحٍ بهذه المساحة أخطر من قِصَر الحديد.', 'info'))

    tp, bt = p.get('top') or {}, p.get('bottom') or {}
    if tp or bt:
        steps.append(step(
            7, 'الشبكتان المعتمَدتان',
            'الوجه العلوي فوق الأعمدة  ·  الوجه السفلي بوسط البحور',
            'علوي: Ø%s @ %s مم  (A_s = %s مم²/م)\n'
            'سفلي: Ø%s @ %s مم  (A_s = %s مم²/م)'
            % (_f(tp.get('db', 0), 0), _f(tp.get('s', 0), 0), _f(tp.get('As', 0), 0),
               _f(bt.get('db', 0), 0), _f(bt.get('s', 0), 0), _f(bt.get('As', 0), 0)),
            'Ø%s@%s  ·  Ø%s@%s'
            % (_f(tp.get('db', 0), 0), _f(tp.get('s', 0), 0),
               _f(bt.get('db', 0), 0), _f(bt.get('s', 0), 0)), '',
            'ACI 318-19 §8.7.2.2',
            'أقصى تباعد min(3h , 450 مم) — ويُضيَّق هنا إلى 300 مم عملياً '
            'لضبط عرض الشقّ في لوحٍ معرّض للتربة والرطوبة.', 'ok'))

    return dict(
        title='الحصيرة (Raft) — الاشتقاق الكامل وفق ACI 318-19',
        intro='الحصيرة ليست أساساً منفرداً كبيراً: مساحتها <b>مفروضة</b> بمسقط '
              'المبنى، وسماكتها يقرّرها <b>القصّ الثاقب</b> تحت أثقل عمود، '
              'وحديدها معكوس الاتجاه عن السقف.',
        steps=renumber(steps),
        result=dict(A=A, h=h, d=d, q_serv=q_serv, q_u=q_u, lam_s=lam_s, bo=bo,
                    Vu=Vu, phiVc=phiVc, M_top=Mt, M_bot=Mb, As_min=As_min,
                    ok=(q_serv <= qa * 1.001 and Vu <= phiVc)),
        refs=['ACI 318-19 §13.3.1.1 — ضغط التربة بأحمال الخدمة',
              'ACI 318-19 جدول 22.6.5.2 — القصّ الثاقب',
              'ACI 318-19 §22.5.5.1.3 — معامل أثر الحجم λs',
              'ACI 318-19 §13.3.4 — تصميم الحصيرة',
              'ACI 318-19 جدول 24.4.3.2 — أدنى حديد 0.0018',
              'ACI 318-19 §20.5.1.3 — الغطاء 75 مم صبّاً على التربة'])


# ═══════════════════ ٩) واجهة موحّدة ═══════════════════
def build(p):
    """نقطة الدخول من الخادم. p = {what, ...}"""
    what = p.get('what')
    if what == 'bars':
        return bar_count(float(p['L']), float(p['s']), float(p.get('cover', 0)),
                         p.get('label', 'البلاطة'), float(p.get('db', 0)))
    if what == 'slab_limits':
        return slab_spacing_limits(float(p['h']), float(p.get('cover', 0.02)),
                                   float(p.get('db', 12)), float(p.get('fy', 420)),
                                   p.get('kind', 'two'))
    if what == 'col_ties':
        return col_ties(float(p['H']), float(p['b']), float(p['h']),
                        float(p['db_long']), float(p['db_tie']),
                        float(p['s_mid']), float(p['s_conf']),
                        p.get('lo'), p.get('hx'), p.get('seismic', True),
                        p.get('ln'))
    if what == 'col_long':
        return col_long(float(p['b']), float(p['h']), float(p['db']),
                        int(p['n_bars']), float(p['Ast']), float(p['fc']),
                        float(p['fy']), float(p.get('cover', 40)),
                        float(p.get('db_tie', 10)), p.get('Pu'), p.get('Mu'),
                        p.get('phiPn'), p.get('phiMn'))
    if what == 'beam_steel':
        return beam_steel(float(p['b']), float(p['h']), float(p['d']),
                          float(p['Mu']), float(p['fc']), float(p['fy']),
                          float(p.get('cover', 40)), float(p.get('db', 16)),
                          float(p.get('db_stir', 10)), p.get('As_used'),
                          p.get('n_bars'), p.get('bw'))
    if what == 'footing':
        return footing(p)
    if what == 'raft':
        return raft(p)
    if what == 'beam_moment':
        return beam_moment(float(p['w']), float(p['L']), p.get('kind', 'interior'),
                           p.get('method', 'coef'), p.get('M'), p.get('V'),
                           p.get('ln'), p.get('face'))
    raise ValueError('نوع غير معروف: %s' % what)

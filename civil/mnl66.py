    out.append(dict(fig='SLAB-2 / SLAB-200 / SLAB-202', name='السقف', rows=rows))

    n = {'ok': 0, 'fail': 0, 'review': 0}
    for s in out:
        for r in s['rows']:
            n[r['state']] = n.get(r['state'], 0) + 1
    return dict(sections=out, counts=n,
                total=sum(n.values()),
                ref='ACI Detailing Manual MNL-66(20) — الأشكال وقوائمها · '
                    'والبنود من ACI 318-19')



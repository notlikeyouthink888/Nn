    # ---- FND-100: الأساس المنفرد ----
    rec = R.get('recommended')
    if rec == 'isolated':
        iso = R['alts']['isolated']; t = iso['typical']
        Bf = t['B'] * 1000.0 if t['B'] < 20 else t['B']     # م ← مم
        col_b = m['col']['b']
        # الطول المتاح لنشر سيخ الأساس خارج وجه العمود، ناقص الغطاء الجانبي
        L1 = (Bf - col_b) / 2.0 - 75.0

# ============================== ١ · العكفات (25.3) ==============================
#: جدول 25.3.1 — أقطار الثني الداخلية للأسياخ الطولية (بمضاعفات db)
BEND_BAR = ((25.0, 6.0), (36.0, 8.0), (57.0, 10.0))
#: جدول 25.3.2 — أقطار الثني الداخلية للأساور والأتاري والكانات
BEND_TIE = ((16.0, 4.0), (25.0, 6.0))


def bend_dia(db, kind='bar'):
    """قطر الثني الداخلي الأدنى — جدول 25.3.1 للأسياخ و25.3.2 للأساور.
    يرجع **القطر** لا نصف القطر (الكود يكتبه قطراً، والموقع يقيسه نصف قطر)."""
    tbl = BEND_TIE if kind == 'tie' else BEND_BAR
    for lim, m in tbl:
        if db <= lim + 1e-9:
            return m * db
    return tbl[-1][1] * db


def hook_ext(db, angle=90, kind='bar'):
    """الامتداد المستقيم بعد الثنية ℓext — جدولا 25.3.1 و25.3.2."""
    if kind == 'tie':
        if angle == 90:
            return max(6.0 * db, 75.0) if db <= 16.0 else 12.0 * db
        if angle == 135:
            return max(6.0 * db, 75.0)
        return max(4.0 * db, 65.0)                       # 180°
    return 12.0 * db if angle == 90 else max(4.0 * db, 65.0)


def hook_full(db, angle=90, kind='bar'):
    """هندسة العكفة كاملة: قطر الثني · نصف القطر لمركز السيخ · الامتداد ·
    الطول المضاف للقصّ (قوس + امتداد) · وطول الإسقاط الظاهر بالرسم.

    الطول المضاف = طول القوس على **محور السيخ** + الامتداد المستقيم، وهذا هو
    ما يُضاف لطول القطع بجدول التقطيع، لا الامتداد وحده كما يُحسب بالموقع غالباً."""
    D = bend_dia(db, kind)
    r_in = D / 2.0                          # نصف قطر داخلي
    r_ax = r_in + db / 2.0                  # نصف قطر محور السيخ
    ext = hook_ext(db, angle, kind)
    arc = math.radians(angle) * r_ax
    # الإسقاط: كم يبرز طرف العكفة عن محور السيخ الأصلي (للرسم ثلاثي الأبعاد)
    a = math.radians(angle)
    px = r_ax * math.sin(a) + ext * math.cos(a)          # باتجاه السيخ
    py = r_ax * (1.0 - math.cos(a)) + ext * math.sin(a)  # عمودياً عليه
    return dict(angle=angle, kind=kind, db=db, bend_dia=D, r_in=r_in, r_ax=r_ax,
                ext=ext, arc=arc, added=arc + ext, proj_x=px, proj_y=py,
                seismic=(angle == 135 and kind == 'tie'),
                clause=('ACI 318M-14 جدول 25.3.2' + (' + 25.3.4 عكفة زلزالية'
                        if angle == 135 else '')) if kind == 'tie'
                       else 'ACI 318M-14 جدول 25.3.1',
                label='عكفة %d° · ثني داخلي %d مم (%gdb) · امتداد %d مم'
                      % (angle, int(D), D / db, int(ext)))


def crosstie(db, angle_a=135, angle_b=90):
    """الأتاري (Crosstie) — ACI 318M-14 المادة 25.3.5:
      (أ) متصل بين طرفيه   (ب) عكفة زلزالية 135° بطرف
      (ج) عكفة قياسية ≥ 90° بالطرف الآخر
      (هـ) الأتاري المتعاقبة على السيخ الطولي نفسه **تُبدَّل جهتها** بالتناوب
           إلا إذا حقّقت 18.6.4.3 أو 25.7.1.6.1 (عكفتان 135° بالطرفين).
    البند (هـ) هو الذي يُنسى بالموقع فتصير كل العكفات 135° بجهة واحدة، فينفتح
    الأتاري من جهته الضعيفة عند انقشار الغطاء."""
    a = hook_full(db, angle_a, 'tie')
    b = hook_full(db, angle_b, 'tie')
    return dict(db=db, end_a=a, end_b=b, added=a['added'] + b['added'],
                alternate=True, clause='ACI 318M-14 25.3.5',
                label='أتاري Ø%d — عكفة 135° بطرف و%d° بالآخر، وتُبدَّل الجهة بالتناوب'
                      % (int(db), angle_b),
                why='العكفة 135° لا تنفتح عند انقشار الغطاء، لكن وضعها كلها بجهة '
                    'واحدة يترك صفّاً كاملاً مربوطاً بعكفة 90° وحدها — فالتبديل '
                    'بالتناوب (25.3.5هـ) يوزّع الضعف ولا يجمعه بخطّ واحد.')


# ======================== ٢ · تركيب الأتاري والأساور (25.7.2) ========================
def tie_db_min(db_long, bundled=False):
    """أدنى قطر للأسوار — ACI 318M-14 المادة 25.7.2.2:
      Ø10 إذا كانت الأسياخ الطولية Ø32 فأصغر · Ø13 لـ Ø36 فأكبر أو المحزومة."""
    return 13.0 if (db_long >= 36.0 or bundled) else 10.0


def tie_spacing(db_long, db_tie, b, h, dagg=20.0):
    """تباعد الأتاري — ACI 318M-14 المادة 25.7.2.1(ب): **الأصغر** من
      16·db الطولي · 48·db الأسوار · أصغر بُعد بالمقطع.
    والخلوص الصافي ≥ (4/3)·مقاس الركام الأكبر (25.7.2.1أ)."""
    lim = [(16.0 * db_long, '16·db الطولي'),
           (48.0 * db_tie, '48·db الأسوار'),
           (min(b, h), 'أصغر بُعد بالمقطع')]
    s, gov = min(lim, key=lambda t: t[0])
    clear_min = (4.0 / 3.0) * dagg + db_tie
    return dict(s=s, govern=gov, all=[dict(v=v, name=n) for v, n in lim],
                clear_min=clear_min, clause='ACI 318M-14 25.7.2.1',
                note='الحاكم: %s = %d مم' % (gov, int(s)))


def tie_support(nb, nh, b, h, cover=40.0, ds=10.0, db=20.0):
    """كم أتاري داخلي يلزم فعلاً — ACI 318M-14 المادة 25.7.2.3:
      (أ) كل سيخ **ركني وكل سيخ بديل** يُسنَد بركن أسوار بزاوية ≤ 135°
      (ب) لا يبعد أي سيخ غير مسنود أكثر من **150 مم خلوصاً** عن سيخ مسنود.

    ترجع عدد الأتاري بكل اتجاه ومواقعها النسبية، والسبب المكتوب — فالبند هذا
    هو الفرق بين عمود يتقشّر غطاؤه ويصمد وعمود تنبعج أسياخه فينهار.

    nb = عدد الأسياخ بالوجه الأفقي (أعلى/أسفل) · nh = بالوجه الرأسي."""
    out = {}
    for key, n, dim in (('x', nb, b), ('y', nh, h)):
        free = dim - 2.0 * cover - 2.0 * ds - db      # المسافة بين مركزَي السيخين الركنيين
        gap = free / max(1, n - 1) - db               # الخلوص الصافي بين سيخين متجاورين
        # كل سيخ بديل مسنود ⇒ الأسياخ الوسطى الزوجية تحتاج سنداً، إلا إن كان
        # الخلوص عن أقرب سيخ مسنود ≤ 150 مم فيُعفى (25.7.2.3ب)
        inner = max(0, n - 2)
        if inner <= 0:
            need = 0; why = 'سيخان بالوجه — كلاهما ركني ومسنود بركن الأسوار'
        elif gap <= 150.0 + 1e-6:
            need = 0
            why = ('الخلوص بين الأسياخ %d مم ≤ 150 مم، فالمادة 25.7.2.3(ب) تعفي '
                   'الأسياخ الوسطى من السند' % int(gap))
        else:
            # سيخ مسنود ثم غير مسنود بالتناوب: عدد الأتاري = عدد الأسياخ الوسطى الفردية
            need = (inner + 1) // 2
            why = ('الخلوص %d مم > 150 مم، فكل سيخ بديل يحتاج ركن أسوار — '
                   '%d أتاري' % (int(gap), need))
        pos = [(i + 1.0) / (n - 1.0) for i in range(n - 2)][::2] if need else []
        out[key] = dict(n=need, gap=gap, pos=pos[:need], bars=n, why=why)
    return dict(x=out['x'], y=out['y'], total=out['x']['n'] + out['y']['n'],
                clause='ACI 318M-14 25.7.2.3',
                why='الأسوار لا توضع «لتربط الحديد» — وظيفتها ثلاث: تحمل القص، '
                    'وتحصر لبّ الخرسانة فيزيد تحمّله ومطاوعته، وتمنع **انبعاج** '
                    'السيخ الطولي للخارج بعد انقشار الغطاء. والثالثة هي سبب '
                    'المادة 25.7.2.3: سيخ غير مسنود بركن أسوار ينبعج وحده ويسحب '
                    'الغطاء معه.')


# ======================= ٣ · قطع حديد الجسور (9.7.3) =======================
def bar_cutoff(ln, d, db_top, db_bot, fc, fy, cover=40.0, spacing=None,
               n_top=4, n_bot=4, simple=False, lateral=True):
    """أين يُقطع الحديد وأين يجب أن يستمر — ACI 318M-14 المادة 9.7.3.

    ln = البحر الصافي بالمتر · d بالمليمتر. ترجع كل الأطوال **بالمتر**.

    البنود المطبَّقة:
      9.7.3.3   يمتد السيخ بعد نقطة عدم الحاجة إليه مسافة = الأكبر من d و12db
      9.7.3.4   الحديد المستمر يمتد ld كاملاً بعد نقطة قطع جاره
      9.7.3.5   **يُمنع** قطع الحديد بمنطقة شدّ إلا بأحد ثلاثة شروط
      9.7.3.8.1 مسند بسيط: **ثلث** الحديد السفلي يدخل المسند ≥ 150 مم
      9.7.3.8.2 مسند آخر: **ربع** الحديد السفلي يدخل ≥ 150 مم، ويُنشر fy عند
                وجه المسند إذا كان الجسر من منظومة مقاومة الأحمال الجانبية
      9.7.3.8.4 **ثلث** الحديد العلوي يمتد بعد نقطة الانقلاب مسافة =
                الأكبر من d و12db و ln/16
    """
    ldt = E.dev_length(db_top, fc, fy, top=True, cover=cover, spacing=spacing)
    ldb = E.dev_length(db_bot, fc, fy, cover=cover, spacing=spacing)
    ext_t = max(d, 12.0 * db_top) / 1000.0
    ext_b = max(d, 12.0 * db_bot) / 1000.0
    inflect = 0.146 * ln            # نقطة الانقلاب التقريبية للبحر المستمر بحمل موزّع
    neg_ext = max(d, 12.0 * db_top, ln * 1000.0 / 16.0) / 1000.0
    frac = (1.0 / 3.0) if simple else (1.0 / 4.0)
    n_in = max(2, int(math.ceil(n_bot * frac)))
    return dict(
        ln=ln, d=d,
        ext_top=ext_t, ext_bot=ext_b,
        ld_top=ldt / 1000.0, ld_bot=ldb / 1000.0,
        inflect=inflect,
        neg_third=dict(n=max(2, int(math.ceil(n_top / 3.0))), ext=neg_ext,
                       at=inflect + neg_ext,
                       rule='ثلث الحديد العلوي يتجاوز نقطة الانقلاب بـ %.2f م '
                            '= الأكبر من d و12db و ln/16' % neg_ext,
                       clause='9.7.3.8.4'),
        pos_into=dict(n=n_in, frac=frac, emb=max(150.0, 0.0),
                      develop_fy=(lateral and not simple),
                      rule=('%s الحديد السفلي (%d سيخ) يدخل المسند %s'
                            % ('ثلث' if simple else 'ربع', n_in,
                               '≥ 150 مم' if not (lateral and not simple)
                               else '≥ 150 مم **وينشر fy عند وجه المسند** لأن '
                                    'الجسر من منظومة مقاومة الأحمال الجانبية')),
                      clause='9.7.3.8.1' if simple else '9.7.3.8.2'),
        no_cut_tension=dict(
            clause='9.7.3.5',
            rule='يُمنع إنهاء حديد الشدّ بمنطقة شدّ إلا بأحد ثلاثة: '
                 '(أ) Vu ≤ ⅔φVn عند نقطة القطع · '
                 '(ب) الحديد المستمر يعطي ضِعف المطلوب و Vu ≤ ¾φVn · '
                 '(ج) أساور زائدة على المطلوب للقص والالتواء بمسافة ¾d من نقطة '
                 'القطع، مساحتها ≥ 0.41·bw·s/fyt وتباعدها ≤ d/(8βb)',
            why='الشقّ الانحنائي ينفتح عند طرف السيخ المقطوع بحمل منخفض، فإن '
                'كان إجهاد الحديد المستمر والقص كلاهما قريباً من حدّه، تحوّل '
                'الشقّ إلى شقّ قطري مبكّر — فينقص تحمّل القص وتضيع المطاوعة.'),
        clause='ACI 318M-14 9.7.3')


def splice_zones(ln, h, sup_w=0.4, seismic=True):
    """أين **يُمنع** لحام/تراكب حديد الجسر — ACI 318M-14 المادة 18.6.3.3.

    يُمنع التراكب: (أ) داخل العقدة · (ب) بمسافة **2h** من وجه العقدة ·
    (ج) بمسافة 2h من أي مقطع حرج يُتوقّع فيه خضوع انحنائي.
    وحيث يُسمح، يجب تطويق منطقة التراكب بكانات تباعدها ≤ الأصغر من d/4 و100 مم.

    هذا البند يُخالَف بالموقع دائماً: الوصلة تُوضع «فوق العمود» لأنه أسهل —
    وهو **بالضبط** المكان الممنوع، لأن العزم السالب أقصى ما يكون هناك.
    الوصلة الصحيحة بوسط البحر حيث العزم السالب صفر تقريباً.
    """
    h_m = h / 1000.0
    ban = 2.0 * h_m + sup_w / 2.0            # من مركز المسند
    free_a = ban
    free_b = ln - ban
    ok = free_b > free_a + 0.3
    return dict(h=h, ban_from_face=2.0 * h_m, ban_from_center=ban,
                zone=[round(free_a, 2), round(free_b, 2)] if ok else None,
                mid=round(ln / 2.0, 2), length=round(max(0.0, free_b - free_a), 2),
                ok=ok, seismic=seismic,
                s_hoop=None,   # يملؤها المتصل بها من d/4 و100 مم
                clause='ACI 318M-14 18.6.3.3',
                label=('منطقة الوصل المسموحة: من %.2f م إلى %.2f م من مركز المسند '
                       '(طولها %.2f م حول وسط البحر)' % (free_a, free_b, free_b - free_a))
                      if ok else
                      'البحر قصير (%.2f م) مقابل عمق الجسر — **لا توجد منطقة وصل '
                      'مسموحة**، فيجب أن يعبر السيخ البحر كاملاً بلا وصلة أو '
                      'يُستعمل وصل ميكانيكي (18.6.3.4).' % ln,
                why='العزم السالب أقصى ما يكون عند وجه العمود، وهناك يُتوقّع الخضوع '
                    'الانحنائي بالزلزال. الوصلة نقطة ضعف بالتماسك، فوضعها بمكان '
                    'الخضوع يعني انزلاق الحديد قبل أن يعطي مطاوعته.')


def seismic_beam(As_top, As_bot, b, d, fy, fc, n_top, n_bot):
    """قواعد الجسر بالإطار المقاوم للعزوم — ACI 318M-14 المادة 18.6.3.

      18.6.3.1 سيخان مستمران بالوجهين على الأقل · ρ ≤ 0.025 · و As ≥ As,min
      18.6.3.2 مقاومة العزم **الموجب** عند وجه العقدة ≥ **نصف** السالب هناك،
               وكلاهما ≥ **ربع** أقصى مقاومة بأي وجه عقدة بالجسر.
    """
    rho_t = As_top / (b * d); rho_b = As_bot / (b * d)
    as_min = E.as_min(fc, fy, b, d)
    half = As_top / 2.0
    quarter = max(As_top, As_bot) / 4.0
    rows = [
        dict(clause='18.6.3.1', name='سيخان مستمران بالوجه العلوي',
             val=n_top, lim=2, ok=n_top >= 2, unit='سيخ'),
        dict(clause='18.6.3.1', name='سيخان مستمران بالوجه السفلي',
             val=n_bot, lim=2, ok=n_bot >= 2, unit='سيخ'),
        dict(clause='18.6.3.1', name='نسبة التسليح العلوي ρ', val=rho_t, lim=0.025,
             ok=rho_t <= 0.025, unit='', fmt='%.4f'),
        dict(clause='18.6.3.1', name='نسبة التسليح السفلي ρ', val=rho_b, lim=0.025,
             ok=rho_b <= 0.025, unit='', fmt='%.4f'),
        dict(clause='9.6.1.2', name='الحديد الأدنى As,min', val=min(As_top, As_bot),
             lim=as_min, ok=min(As_top, As_bot) >= as_min - 1e-6, unit='مم²', ge=True),
        dict(clause='18.6.3.2', name='الموجب عند وجه العقدة ≥ نصف السالب',
             val=As_bot, lim=half, ok=As_bot >= half - 1e-6, unit='مم²', ge=True),
        dict(clause='18.6.3.2', name='كلاهما ≥ ربع أقصى مقاومة بأي وجه',
             val=min(As_top, As_bot), lim=quarter,
             ok=min(As_top, As_bot) >= quarter - 1e-6, unit='مم²', ge=True),
    ]
    return dict(rows=rows, ok=all(r['ok'] for r in rows), rho_top=rho_t, rho_bot=rho_b,
                As_bot_need=half, clause='ACI 318M-14 18.6.3',
                why='الجسر بالإطار الزلزالي ينقلب عزمه: الوجه الذي يُشدّ من الأعلى '
                    'بالحمل الثقلي يُشدّ من الأسفل عند اهتزاز الأرض بالاتجاه '
                    'الآخر. ولهذا يوجب الكود حديداً سفلياً عند العقدة لا يقل عن '
                    'نصف العلوي — وهذا ما يُنسى بالمخططات الثقلية.')


# ===================== ٤ · توزيع حديد الأساس (13.3.3.3) =====================
def footing_bands(B, L, As_short):
    """توزيع حديد الاتجاه القصير بالأساس المستطيل — ACI 318M-14 المادة 13.3.3.3:
      γs = 2/(β+1) حيث β = الضلع الطويل ÷ القصير
      γs·As يوزَّع بانتظام على **شريط أوسط عرضه = الضلع القصير** بمركز العمود،
      والباقي (1−γs)·As يوزَّع على ما تبقّى خارج الشريط.

    السبب: الأساس المستطيل ينحني أكثر قرب العمود، فتوزيع الحديد بانتظام يترك
    الوسط ناقصاً والأطراف زائدة. B وL بالمتر · As بالمم²."""
    short, long_ = min(B, L), max(B, L)
    beta = long_ / max(0.001, short)
    gs = 2.0 / (beta + 1.0)
    band = gs * As_short
    outer = (1.0 - gs) * As_short
    return dict(beta=beta, gamma_s=gs, band_width=short, band_As=band,
                outer_As=outer, outer_width=max(0.0, long_ - short),
                uniform=(abs(beta - 1.0) < 0.02),
                clause='ACI 318M-14 13.3.3.3',
                label=('الأساس مربّع — التوزيع منتظم بالاتجاهين' if abs(beta - 1.0) < 0.02
                       else 'β = %.2f ⇒ γs = %.3f — %.0f%% من حديد الاتجاه القصير '
                            'يتركّز بشريط أوسط عرضه %.2f م، والباقي على الأطراف'
                            % (beta, gs, gs * 100, short)))


# ======================== ٥ · الكانتيليفر (الشناشيل) ========================
def cantilever(Lc, trib, wD, wL, b, h, fc, fy, cover=40.0, ds=10.0,
               parapet=0.0, back_span=0.0, seismic=True):
    """تصميم جسر كانتيليفر كامل — وهو **الحالة التي تُخطئ بالموقع أكثر من غيرها**
    لأن حديده كله **علوي**، والحدّاد المعتاد على الجسور العادية يضعه بالأسفل.

    البنود:
      جدول 9.3.1.1  أدنى عمق للكانتيليفر = **ℓ/8** (لا ℓ/16 كالبحر البسيط)
      9.7.3.3       لا يلزم تمديد d أو 12db عند **الطرف الحرّ** (استثناء صريح)
      25.4.2/25.4.3 الحديد العلوي يُنشر ld كاملاً **داخل البحر الخلفي**، وإن لم
                    يكفِ فبعكفة 90° هابطة داخل العمود (ldh)
      9.6.1.2       As,min على الوجه العلوي (وجه الشدّ)
      9.7.7         التماسك: حديد سفلي مستمر داخل المسند
      24.3.2        التحكم بالشقوق — الوجه العلوي معرّض للمطر بالشناشيل
      22.5          القص أقصى ما يكون عند **وجه المسند** لا بالوسط

    Lc = بروز الكانتيليفر بالمتر · trib = عرض الشريحة الحاملة بالمتر
    parapet = حمل خطّي على الطرف الحرّ kN/م (درابزين · جدار).
    """
    h = float(h)
    hmin = Lc * 1000.0 / 8.0 * (0.4 + fy / 700.0)        # جدول 9.3.1.1 معدَّلاً لـ fy
    d = h - cover - ds - 8.0
    sw = b * h / 1e6 * 24.0                               # kN/م وزن ذاتي
    w_ser = wD * trib + sw
    wu = 1.2 * w_ser + 1.6 * wL * trib
    Pu_tip = 1.2 * parapet
    # العزم والقص عند وجه المسند
    Mu = wu * Lc * Lc / 2.0 + Pu_tip * Lc
    Vu = wu * Lc + Pu_tip
    # شريحة عرضها متر فأكثر تُصمَّم **كبلاطة** لا كجسر: الحديد الأدنى بها هو
    # حديد الانكماش 0.0018·Ag (7.6.1.1) لا 0.25√f'c/fy·bw·d، والتسليح يُوصف
    # بالتباعد لا بعدد الأسياخ.
    wide = b >= 800.0
    fl = E.flexure(Mu, b, d, fc, fy, h, min_rule='slab' if wide else 'beam')
    if wide:
        fl['bars'] = E.bar_spacing(fl['As_req'], dbs=(10, 12, 16, 20, 25), smax=200.0)
    else:
        fl['bars'] = E.pick_bars(fl['As_req'], width=b)
    sh = E.shear(Vu, b, d, fc, fy, db_stirrup=int(ds),
                 rho_w=fl['bars']['As'] / (b * d), min_stirrups=not wide)
    # الترخيم: الكانتيليفر يترخّم **بمكعّب** طوله ونصيبه من دوران المسند
    Ie, Ig, Icr, Mcr = E.cracked_I(b, h, d, fl['bars']['As'], fc,
                                   max(1.0, w_ser * Lc * Lc / 2.0 + parapet * Lc))
    Ec = E.Ec(fc)
    d_im = (w_ser * (Lc ** 4) * 1e12 / 8.0 + parapet * (Lc ** 3) * 1e9 / 3.0) \
        / (Ec * max(Ie, 1.0))                             # مم
    share = (wD * trib + sw) / max(0.001, w_ser + wL * trib)
    dfl = E.deflection_check(2.0 * Lc, d_im * share, d_im * (1.0 - share),
                             rho_p=0.0, months=60, case='attach_dmg')
    # النشر داخل البحر الخلفي
    dbt = fl['bars']['db']
    ld = E.dev_length(dbt, fc, fy, top=True, cover=cover)
    ldh = E.hook_dev(dbt, fc, fy, confined=True, inside_col=True)
    need_hook = (back_span * 1000.0 < ld) if back_span else True
    # الوجه السفلي: بالبروز هو وجه **الضغط**، فلا يحمل حديد شدّ. ما يوضع فيه
    # حديد انكماش وحرارة (7.6.1.1 = 0.0018·Ag) وحديد تماسك مستمر داخل المسند
    # (9.7.7) — لا نصف التسليح العلوي كما يُرسم أحياناً بالخطأ.
    if wide:
        as_min = 0.0018 * b * h
        bot = E.bar_spacing(as_min, dbs=(10, 12, 16), smax=250.0)
        as_min_face = as_min
    else:
        as_min = E.as_min(fc, fy, b, d)
        as_min_face = as_min
        bot = E.pick_bars(max(0.0018 * b * h, fl['bars']['As'] / 4.0), width=b, nmin=2)
    hk = hook_full(dbt, 90, 'bar')
    ties = tie_spacing(dbt, ds, b, h)
    return dict(
        L=Lc, b=b, h=h, hmin=hmin, ok_h=h >= hmin - 1e-6, d=d, trib=trib,
        wu=wu, w_ser=w_ser, parapet=parapet, Mu=Mu, Vu=Vu, sw=sw,
        flex=fl, shear=sh, top=fl["bars"], bottom=bot, as_min=as_min_face, wide=wide,
        defl=dfl, d_imm=d_im, Ie=Ie, Ig=Ig,
        anchor=dict(ld=ld / 1000.0, ldh=ldh / 1000.0, need_hook=need_hook,
                    back_span=back_span, hook=hk,
                    rule=('البحر الخلفي %.2f م %s طول النشر %.2f م'
                          % (back_span, 'أقصر من' if need_hook else 'يكفي',
                             ld / 1000.0))
                         + (' — فيُعكف الحديد 90° هابطاً داخل العمود بطول %.2f م '
                            '(ldh)' % (ldh / 1000.0) if need_hook else
                            ' — فيمتد مستقيماً بلا عكفة')),
        ties=ties, cover=cover, ds=ds,
        rules=[
            dict(c='جدول 9.3.1.1', t='أدنى عمق للكانتيليفر ℓ/8',
                 v='%d مم' % int(h), l='≥ %d مم' % int(hmin), ok=h >= hmin - 1e-6,
                 why='الكانتيليفر يترخّم أضعاف البحر البسيط بنفس الطول، فالكود '
                     'يوجب له عمقاً مضاعفاً: ℓ/8 مقابل ℓ/16.'),
            dict(c='9.7.3', t='**كل** الحديد الرئيسي على الوجه العلوي',
                 v='%s علوي' % fl['bars']['label'], l='الشدّ بالأعلى', ok=True,
                 why='عزم الكانتيليفر سالب على طوله كله — الوجه المشدود هو '
                     'العلوي. وضع الحديد بالأسفل يعني انهياراً فورياً عند '
                     'فكّ القالب، وهذا أشيع خطأ بالشناشيل والبلكونات.'),
            dict(c='25.4.2 / 25.4.3', t='نشر الحديد العلوي داخل البحر الخلفي',
                 v='%.2f م' % (ld / 1000.0),
                 l='ld كاملاً من وجه المسند', ok=True,
                 why='الكانتيليفر معلّق من البحر الخلفي — إن لم يُنشر حديده هناك '
                     'انسلّ من العقدة وسقط، والمقطع سليم.'),
            dict(c='9.7.3.3', t='لا تمديد مطلوب عند الطرف الحرّ',
                 v='ينتهي الحديد بعكفة 90° هابطة', l='استثناء صريح بالبند',
                 ok=True,
                 why='البند يستثني «الطرف الحرّ للكانتيليفر» من تمديد d أو 12db، '
                     'لكن العكفة الهابطة تُوضع عملياً لتثبيت الأسوار الطرفية '
                     'ولحماية الطرف من التشقّق.'),
            dict(c='22.5', t='القص أقصى ما يكون عند وجه المسند',
                 v='Vu = %.0f kN' % Vu, l=sh['label'], ok=sh['ok'],
                 why='بعكس البحر البسيط، لا يوجد بالكانتيليفر مقطع قصّه صفر إلا '
                     'الطرف الحرّ — فالأساور تُكثّف عند المسند لا عند الوسط.'),
            dict(c='9.7.7', t='حديد التماسك السفلي داخل المسند',
                 v=bot['label'], l='مستمر داخل المسند', ok=True,
                 why='لو تشقّق الوجه العلوي، الحديد السفلي المستمر يمنع '
                     'الانفصال الكامل ويعطي مساراً بديلاً.'),
        ],
        clause='ACI 318M-14 9.3.1.1 · 9.7.3 · 25.4 · 22.5 · 9.7.7')
